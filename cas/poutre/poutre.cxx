/*!
 * \return the options of BoomerAMG given as `Name=value` separated by
 * commas, integers or reals (with a dot or an exponent), the verbosity
 * level being null
 * \param[in] o: options
 */
static mfem_mgis::Parameters parseBoomerAMGOptions(const std::string& o) {
  auto params = mfem_mgis::Parameters{{"VerbosityLevel", 0}};
  auto start = std::string::size_type{};
  while (start < o.size()) {
    const auto end = std::min(o.find(',', start), o.size());
    const auto option = o.substr(start, end - start);
    const auto equal = option.find('=');
    if (equal == std::string::npos) {
      std::cerr << "invalid option of BoomerAMG '" << option << "'\n";
      std::exit(EXIT_FAILURE);
    }
    const auto name = option.substr(0, equal);
    const auto value = option.substr(equal + 1);
    if (value.find_first_of(".eE") != std::string::npos) {
      params.replaceOrInsert(name, std::stod(value));
    } else {
      params.replaceOrInsert(name, std::stoi(value));
    }
    start = end + 1;
  }
  return params;
}  // end of parseBoomerAMGOptions

int main(int argc, char** argv) {
  using namespace mfem_mgis;
  initialize(argc, argv);
  const char* mesh = "beam-tet.mesh";
  const char* library = "src/libBehaviour.so";
  const char* linear_solver = "pcg-amg";
  const char* behaviour_integration = "";
  const char* non_linear_solver = "newton";
  const char* fixed_point_method = "elastic";
  const char* acceleration = "anderson";
  const char* elastic_operator_linear_solver = "problem";
  const char* amg_options = "";
  auto anderson_depth = 4;
  auto elastic_operator_once = false;
  auto prediction_by_elastic_operator = false;
  auto parallel = true;
  auto refinements = 3;
  auto steps = 10;
  auto max_iterations = 50;
  auto prediction = true;
  auto profiling = false;
  auto update_period = 1;
  auto displacement = real{0.5};
  auto relative_tolerance = real{1e-8};
  auto linear_tolerance = real{1e-10};
  auto expected_norm = real{-1};
  auto norm_tolerance = real{1e-6};
  mfem::OptionsParser args(argc, argv);
  declareDefaultOptions(args);
  args.AddOption(&mesh, "-m", "--mesh", "Mesh file.");
  args.AddOption(&library, "-l", "--library", "Behaviour library.");
  args.AddOption(&linear_solver, "-ls", "--linear-solver",
                 "Linear solver: mumps (parallel), umfpack (sequential), "
                 "pcg-amg (parallel, PCG of hypre and BoomerAMG), cg-amg "
                 "(parallel, conjugate gradient of MFEM and BoomerAMG built on "
                 "the assembled tangent operator) or cg-jacobi "
                 "(conjugate gradient of MFEM and Jacobi preconditioner, "
                 "usable with the tangent operator applied without "
                 "assembly).");
  args.AddOption(&behaviour_integration, "-bi", "--behaviour-integration",
                 "Integration of the behaviour: PointByPoint or Batch "
                 "(required by a library generated by the generic-parallel "
                 "interface). By default, the value given by the environment "
                 "variable MFEM_MGIS_BEHAVIOUR_INTEGRATION, or PointByPoint.");
  args.AddOption(&non_linear_solver, "-nls", "--non-linear-solver",
                 "Non linear solver: newton or fixed-point.");
  args.AddOption(&fixed_point_method, "-fpm", "--fixed-point-method",
                 "Method of the fixed point solver: elastic (fixed point on "
                 "the elastic operator), modified-newton or newton-k0 "
                 "(Newton, conjugate gradient preconditioned by the linear "
                 "solver of the elastic operator, -els, with the tolerance of "
                 "the linear solver, -lt; no acceleration).");
  args.AddOption(&acceleration, "-acc", "--acceleration",
                 "Acceleration of the fixed point solver: none, anderson or "
                 "cast3m.");
  args.AddOption(&anderson_depth, "-ad", "--anderson-depth",
                 "Depth of Anderson's method.");
  args.AddOption(&elastic_operator_linear_solver, "-els",
                 "--elastic-operator-linear-solver",
                 "Linear solver of the elastic operator of the fixed point "
                 "solver: problem (the linear solver of the problem, set up "
                 "at each step), amg (one cycle of BoomerAMG), pcg-amg or "
                 "mumps.");
  args.AddOption(&elastic_operator_once, "-k0", "--elastic-operator-once",
                 "-no-k0", "--no-elastic-operator-once",
                 "Elastic operator of the fixed point solver assembled once.");
  args.AddOption(&prediction_by_elastic_operator, "-pk0",
                 "--prediction-by-elastic-operator", "-no-pk0",
                 "--no-prediction-by-elastic-operator",
                 "Elastic predictions of the fixed point solver solved by the "
                 "conjugate gradient preconditioned by the linear solver of "
                 "the elastic operator (tolerance of the linear solver).");
  args.AddOption(&amg_options, "-amgo", "--amg-options",
                 "Options of all the BoomerAMG preconditioners and solvers, "
                 "as Name=value separated by commas (see the HypreBoomerAMG "
                 "preconditioner of mfem-mgis), for instance "
                 "RelaxationType=8,StrengthThreshold=0.5.");
  args.AddOption(&linear_tolerance, "-lt", "--linear-tolerance",
                 "Relative tolerance of the iterative linear solver.");
  args.AddOption(&parallel, "-p", "--parallel", "-no-p", "--no-parallel",
                 "Parallel computation.");
  args.AddOption(&refinements, "-r", "--refinements",
                 "Number of uniform refinements of the mesh.");
  args.AddOption(&steps, "-n", "--steps", "Number of time steps.");
  args.AddOption(&update_period, "-pu", "--preconditioner-update-period",
                 "Period of the updates of the preconditioner built on the "
                 "assembled tangent operator (linear solver cg-amg).");
  args.AddOption(&max_iterations, "-mi", "--max-iterations",
                 "Maximum number of Newton iterations per step.");
  args.AddOption(&prediction, "-pr", "--prediction", "-no-pr",
                 "--no-prediction",
                 "Elastic prediction at the beginning of each step.");
  args.AddOption(&displacement, "-u", "--displacement",
                 "Transverse displacement imposed at the end of the beam.");
  args.AddOption(&relative_tolerance, "-rt", "--relative-tolerance",
                 "Relative tolerance of the Newton solver.");
  args.AddOption(&expected_norm, "-en", "--expected-norm",
                 "Expected norm of the final solution (no check if "
                 "negative).");
  args.AddOption(&norm_tolerance, "-nt", "--norm-tolerance",
                 "Relative tolerance of the comparison to the expected norm.");
  args.AddOption(&profiling, "-prof", "--profiling", "-no-prof",
                 "--no-profiling",
                 "Print the time spent in each phase of the computation.");
  args.Parse();
  if (!args.Good()) {
    args.PrintUsage(std::cerr);
    abort(EXIT_FAILURE);
  }
  auto ctx = Context{};
  auto or_die = ctx.getFatalFailureHandler();
  const auto amg = parseBoomerAMGOptions(amg_options);
  ctx.enableProfiling(profiling);
  auto success = true;
  {
    // the other options of mfem-mgis (computations by kernels) are given
    // by their environment variables
    auto parameters = Parameters{{"MeshFileName", mesh},
                                 {"FiniteElementFamily", "H1"},
                                 {"FiniteElementOrder", 1},
                                 {"UnknownsSize", 3},
                                 {"NumberOfUniformRefinements", refinements},
                                 {"Hypothesis", "Tridimensional"},
                                 {"Parallel", parallel}};
    if (!std::string_view{behaviour_integration}.empty()) {
      parameters.insert(ctx, "BehaviourIntegration",
                        std::string{behaviour_integration}) |
          or_die;
    }
    const auto nls = std::string{non_linear_solver};
    if (nls == "fixed-point") {
      const auto fpm = std::string_view{fixed_point_method};
      if ((fpm != "elastic") && (fpm != "modified-newton") &&
          (fpm != "newton-k0")) {
        std::cerr << "invalid method of the fixed point solver '" << fpm
                  << "'\n";
        abort(EXIT_FAILURE);
      }
      auto options = Parameters{
          {"Method", fpm == "elastic"           ? "ElasticOperator"
                     : fpm == "modified-newton" ? "ModifiedNewton"
                                                : "NewtonK0"},
          {"ElasticOperatorUpdate",
           elastic_operator_once ? "Once" : "EachResolution"}};
      const auto a = std::string{acceleration};
      if (fpm == "newton-k0") {
        options.insert(ctx, "TangentLinearSolver",
                       Parameters{{"RelativeTolerance", linear_tolerance},
                                  {"MaximumNumberOfIterations", 2000}}) |
            or_die;
      } else if (a == "anderson") {
        options.insert(ctx, "Acceleration",
                       Parameters{{"Anderson",
                                   Parameters{{"Depth", anderson_depth}}}}) |
            or_die;
      } else if (a == "cast3m") {
        options.insert(ctx, "Acceleration", "Cast3M") | or_die;
      } else if (a != "none") {
        std::cerr << "invalid acceleration '" << a << "'\n";
        abort(EXIT_FAILURE);
      }
      const auto els = std::string{elastic_operator_linear_solver};
      if (els == "amg") {
        options.insert(ctx, "ElasticOperatorLinearSolver",
                       Parameters{{"HypreBoomerAMG", amg}}) |
            or_die;
      } else if (els == "pcg-amg") {
        options.insert(
            ctx, "ElasticOperatorLinearSolver",
            Parameters{
                {"HyprePCG",
                 Parameters{{"Tolerance", linear_tolerance},
                            {"MaximumNumberOfIterations", 2000},
                            {"Preconditioner",
                             Parameters{{"Name", "HypreBoomerAMG"},
                                        {"Options", amg}}}}}}) |
            or_die;
      } else if (els == "mumps") {
        options.insert(ctx, "ElasticOperatorLinearSolver",
                       Parameters{{"MUMPSSolver",
                                   Parameters{{"Symmetric", true}}}}) |
            or_die;
      } else if (els != "problem") {
        std::cerr << "invalid linear solver of the elastic operator '" << els
                  << "'\n";
        abort(EXIT_FAILURE);
      }
      if (prediction_by_elastic_operator) {
        options.insert(
            ctx, "PredictionLinearSolver",
            Parameters{
                {"ElasticOperator",
                 Parameters{{"RelativeTolerance", linear_tolerance}}}}) |
            or_die;
      }
      parameters.insert(ctx, "NonLinearSolver",
                        Parameters{{"FixedPoint", options}}) |
          or_die;
    } else if (nls != "newton") {
      std::cerr << "invalid non linear solver '" << nls << "'\n";
      abort(EXIT_FAILURE);
    }
    auto problem =
        construct<NonLinearEvolutionProblem>(ctx, parameters) | or_die;
    // the two element attributes of beam-tet.mesh
    for (const auto m : {1, 2}) {
      problem.addBehaviourIntegrator(ctx, "Mechanics", m, library,
                                     "IsotropicLinearHardeningPlasticity") |
          or_die;
      auto& mat = problem.getMaterial(ctx, m, 0) | or_die;
      for (auto* s : {&mat.s0, &mat.s1}) {
        mgis::behaviour::setExternalStateVariable(ctx, *s, "Temperature",
                                                  293.15) |
            or_die;
      }
    }
    // clamped end, transverse displacement at the other end
    for (const auto c : {0, 1, 2}) {
      problem.addUniformDirichletBoundaryCondition(
          ctx, {{"Boundary", 1}, {"Component", c}}) |
          or_die;
    }
    problem.addUniformDirichletBoundaryCondition(
        ctx, {{"Boundary", 2},
              {"Component", 1},
              {"LoadingEvolution",
               [displacement](const real t) { return displacement * t; }}}) |
        or_die;
    if (prediction) {
      auto pp = PredictionPolicy{};
      pp.strategy = PredictionStrategy::BEGINNING_OF_TIME_STEP_PREDICTION;
      pp.prediction_operator = PredictionOperator::ELASTIC;
      problem.setPredictionPolicy(pp);
    }
    const auto ls = std::string{linear_solver};
    if (ls == "mumps") {
      problem.setLinearSolver(ctx, "MUMPSSolver", {{"Symmetric", true}}) |
          or_die;
    } else if (ls == "umfpack") {
      problem.setLinearSolver(ctx, "UMFPackSolver", {}) | or_die;
    } else if (ls == "pcg-amg") {
      problem.setLinearSolver(
          ctx, "HyprePCG",
          {{"VerbosityLevel", 0},
           {"Tolerance", linear_tolerance},
           {"MaximumNumberOfIterations", 2000},
           {"Preconditioner",
            Parameters{{"Name", "HypreBoomerAMG"}, {"Options", amg}}}}) |
          or_die;
    } else if (ls == "cg-amg") {
      // conjugate gradient of MFEM, BoomerAMG built on the assembled tangent
      // operator every `update_period` Newton iterations: with the tangent
      // operator applied without assembly, the Krylov products use the
      // action of the kernels
      problem.setLinearSolver(
          ctx, "CGSolver",
          {{"VerbosityLevel", 0},
           {"RelativeTolerance", linear_tolerance},
           {"AbsoluteTolerance", 0.},
           {"MaximumNumberOfIterations", 2000},
           {"Preconditioner",
            Parameters{
                {"Name", "AssembledOperator"},
                {"Options",
                 Parameters{{"UpdatePeriod", update_period},
                            {"Preconditioner",
                             Parameters{{"Name", "HypreBoomerAMG"},
                                        {"Options", amg}}}}}}}}) |
          or_die;
    } else if (ls == "cg-jacobi") {
      // conjugate gradient of MFEM with a Jacobi preconditioner: usable with
      // the tangent operator applied without assembly
      // (TangentOperatorComputation set to MatrixFree)
      problem.setLinearSolver(
          ctx, "CGSolver",
          {{"VerbosityLevel", 0},
           {"RelativeTolerance", linear_tolerance},
           {"AbsoluteTolerance", 0.},
           {"MaximumNumberOfIterations", 100000},
           {"Preconditioner",
            Parameters{{"Name", "OperatorJacobiSmoother"}}}}) |
          or_die;
    } else {
      std::cerr << "invalid linear solver '" << ls << "'\n";
      abort(EXIT_FAILURE);
    }
    problem.setSolverParameters(
        ctx, {{"VerbosityLevel", 0},
              {"RelativeTolerance", relative_tolerance},
              {"AbsoluteTolerance", 0.},
              {"MaximumNumberOfIterations", max_iterations}}) |
        or_die;
    // loop over the time steps
    const auto dt = real{1} / steps;
    auto t = real{0};
    auto iterations = std::vector<int>{};
    const auto start = std::chrono::steady_clock::now();
    for (int i = 0; i != steps; ++i) {
      const auto r = problem.solve(ctx, t, dt);
      if (!r.status) {
        std::cerr << "step " << i + 1 << ": not converged\n";
        abort(EXIT_FAILURE);
      }
      iterations.push_back(r.iterations);
      problem.update(ctx) | or_die;
      t += dt;
    }
    auto total =
        std::chrono::duration<double>(std::chrono::steady_clock::now() - start)
            .count();
    // norm of the final solution, to compare the solvers
    const auto& u = problem.getUnknowns(bts);
    auto unorm = mfem::InnerProduct(u, u);
#ifdef MFEM_USE_MPI
    if (parallel) {
      MPI_Allreduce(MPI_IN_PLACE, &unorm, 1, MPI_DOUBLE, MPI_SUM,
                    MPI_COMM_WORLD);
      MPI_Allreduce(MPI_IN_PLACE, &total, 1, MPI_DOUBLE, MPI_MAX,
                    MPI_COMM_WORLD);
    }
#endif /* MFEM_USE_MPI */
    const auto& fed = problem.getFiniteElementDiscretization();
    const auto ndofs =
        fed.describesAParallelComputation()
            ? static_cast<long long>(
                  fed.getFiniteElementSpace<true>().GlobalTrueVSize())
            : static_cast<long long>(
                  fed.getFiniteElementSpace<false>().GetTrueVSize());
    if (isMainProcess(fed)) {
      auto sum = 0;
      std::cout << "dofs " << ndofs << " | nls " << nls << " | ls " << ls
                << " | ||u|| "
                << std::setprecision(10) << std::sqrt(unorm)
                << " | iterations per step:";
      for (const auto n : iterations) {
        std::cout << ' ' << n;
        sum += n;
      }
      std::cout << " | total " << sum << '\n'
                << std::fixed << std::setprecision(3) << "time " << total
                << " s\n";
    }
    if ((expected_norm >= 0) && (std::abs(std::sqrt(unorm) - expected_norm) >
                                 norm_tolerance * expected_norm)) {
      if (isMainProcess(fed)) {
        std::cerr << "the norm of the solution differs from the expected one ("
                  << std::setprecision(10) << expected_norm << ")\n";
      }
      success = false;
    }
    if (profiling) {
      Profiler::OutputManager::printTimeTable(ctx);
    }
  }  // the problem is destroyed before the finalization of MPI
  finalize();
  return success ? EXIT_SUCCESS : EXIT_FAILURE;
}  // end of main
