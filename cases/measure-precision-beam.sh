#!/bin/bash
# Precision float against double on the CPU (task 9b): beam of the
# prototype (cases/beam), `REFINEMENTS` refinements (4 by default, 111,843
# unknowns), `STEPS` steps (10), Newton, PCG of hypre and BoomerAMG
# (tolerance 1e-4), `PROCESSES` processes (2) bound to the cores `CPUS`
# (0,1), each computation repeated `REPETITIONS` times (3).
#
# The two builds only differ by the precision: twin spack environments
# deps/spack/mmm-double-cpu and deps/spack/mmm-float-cpu (MFEM, hypre and
# MUMPS in double or in single precision, without CUDA), MGIS in double
# (install/mgis) or in float (install/mgis-float), mfem-mgis built against
# each of them, cases built against each mfem-mgis (build/cases-double-cpu
# and build/cases-float, or the directories given by `CASES_DOUBLE` and
# `CASES_FLOAT`).
#
# Newton criteria: the one of the case (1e-8) in double only, as reference,
# then `CRITERION` (1e-4 by default) for both precisions, to compare the
# times at equal criterion. In float, the criterion of the case, bounded to
# 100 ε = 1.2e-5 by mfem-mgis, is not reached at r4: the relative residual
# levels off around 1.3e-5 and Newton stops after 50 iterations.
#
# With `DEVICE=gpu`: everything on the GPU (`--execution gpu`, behaviour of
# the `cuda` backend), one process on the core `CPUS` (0), builds
# build/cases-9b (double, mfem-mgis installed separately in
# install/mfem-mgis-9b, environment mmm-gpu) and build/cases-float-gpu
# (float, environment mmm-float-gpu: MFEM and hypre in single precision
# with CUDA).
#
# usage: cases/measure-precision-beam.sh [results directory]
set -u
P=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$P/results/precision-beam-$(date +%Y-%m-%d-%H%M)}
mkdir -p "$out"
SPACK=${SPACK:-$HOME/Bureau/spack-mmm/bin/spack}
device=${DEVICE:-cpu}
if [ "$device" = gpu ]; then
  np=${PROCESSES:-1}
  cpus=${CPUS:-0}
else
  np=${PROCESSES:-2}
  cpus=${CPUS:-0,1}
fi
repetitions=${REPETITIONS:-3}
refinements=${REFINEMENTS:-4}
steps=${STEPS:-10}
criterion=${CRITERION:-1e-4}
declare -A mgis=([double]=$P/install/mgis [float]=$P/install/mgis-float)
if [ "$device" = gpu ]; then
  declare -A cases=([double]=${CASES_DOUBLE:-$P/build/cases-9b}
                    [float]=${CASES_FLOAT:-$P/build/cases-float-gpu})
  declare -A environment=([double]=$P/deps/spack/mmm-gpu
                          [float]=$P/deps/spack/mmm-float-gpu)
  # behaviour generated by the cuda backend of the generic-parallel interface
  device_options=(--execution gpu
    -l generic-parallel-cuda/src/libGenericParallelBehaviour-cuda.so)
else
  declare -A cases=([double]=${CASES_DOUBLE:-$P/build/cases-double-cpu}
                    [float]=${CASES_FLOAT:-$P/build/cases-float})
  declare -A environment=([double]=$P/deps/spack/mmm-double-cpu
                          [float]=$P/deps/spack/mmm-float-cpu)
  device_options=()
fi
{
  echo "beam r$refinements, $steps steps, $device, $np processes on the cores $cpus,"
  echo "$repetitions repetitions; $(date)"
  echo "machine: $(nproc) threads; load: $(cut -d' ' -f1-3 /proc/loadavg)"
} | tee "$out/summary.txt"
# usage: run <precision> <name> <repetition> <options...>
run() {
  local precision=$1 name=$2 i=$3
  shift 3
  local mpi
  mpi=$(SPACK_DISABLE_LOCAL_CONFIG=1 "$SPACK" -e "${environment[$precision]}" \
    location -i mpi)
  local B=${cases[$precision]}/beam
  if [ ! -x "$B/beam" ]; then
    echo "== $name: executable $B/beam missing" | tee -a "$out/summary.txt"
    return 1
  fi
  echo "== $name-$i: $*" | tee -a "$out/summary.txt"
  # clean environment: only MPI, TFEL and the MGIS of the precision;
  # taskset around mpirun, which binds each process to a core of the
  # allowed set
  (cd "$B" && env -i HOME="$HOME" PATH="$mpi/bin:/usr/bin:/bin" \
    LD_LIBRARY_PATH="$P/install/tfel-mmm-gpu/lib:${mgis[$precision]}/lib" \
    taskset -c "$cpus" timeout 3600 mpirun -n "$np" ./beam \
    -r "$refinements" -n "$steps" -ls pcg-amg -lt 1e-4 -prof \
    "${device_options[@]}" "$@") \
    < /dev/null > "$out/$name-$i.txt" 2>&1
  echo "   status $?" | tee -a "$out/summary.txt"
  /usr/bin/grep -E "^dofs|^time" "$out/$name-$i.txt" | sed 's/^/   /' |
    tee -a "$out/summary.txt"
}
# the precisions alternate at each repetition, so that a drift of the
# machine affects both in the same way
for i in $(seq 1 "$repetitions"); do
  run double double-case-criterion "$i"
  for precision in double float; do
    run "$precision" "$precision-criterion-$criterion" "$i" -rt "$criterion"
  done
done
echo "results in $out"
