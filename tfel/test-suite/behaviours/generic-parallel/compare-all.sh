run SingleCrystal_DD_FCC_Tridimensional \
  --material-properties=208000,208000,208000,0.3,0.3,0.3,80000,80000,80000,105,2.5e-7,5,1e-3,0.13,0.005,1e6,0.35,2.54e-7,80000 \
