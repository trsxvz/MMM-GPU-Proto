# Definitions shared by the scripts comparing the `generic-parallel`
# interface to the `generic` interface (compare-all.sh, compare-tdls.sh),
# which are sourced with the following arguments:
#
# compare_executable batch_library [pattern]
#
# The optional pattern (an extended regular expression) selects the tested
# functions.
#
# The `run` function calls the comparison program with the reference and
# batch libraries and its arguments: the function, the sizes of the
# gradients, thermodynamic forces, material properties, internal state
# variables, external state variables and tangent operator, the strain
# amplitude, the material properties, the temperature and options (see
# compare.cxx). All the comparisons are run, and the `status` variable is
# non-zero if one of them fails.
compare=$1
library=$2
pattern=${3:-.}
status=0
# libraries generated by the `generic` and `generic-parallel` interfaces
reference=src/libBehaviour.so
batch=$library
run() {
  echo "$1" | grep -qE "$pattern" || return 0
  echo "$*"
  "$compare" "$reference" "$batch" "$@" || status=1
}
