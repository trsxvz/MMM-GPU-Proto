  void initialize(int& argc, MainFunctionArguments& argv) {
    static bool first = true;
    if (first) {
      mgis::setDefaultLogStream(mfem_mgis::getOutputStream());
      // the execution settings and the solver overrides are read before the
      // initialization of MPI, which an invalid option leaves untouched
      internals::readExecutionSettings(argc, argv);
      internals::readSolverOverrides(argc, argv);
      MPI_Init(&argc, &argv);
      try {
        internals::checkSolverOverrides(MPI_COMM_WORLD);
      } catch (...) {
        MPI_Finalize();
        throw;
      }
      // with hypre on the host, neither the initialization of hypre nor the
      // configuration of the device of MFEM make hypre use the GPU (nor
      // initialize its libraries on the GPU), even if the device is
      // configured before (by the program or by the variable MFEM_DEVICE).
      // The location of the linear solvers decides the memory of hypre.
      auto hypre_on_host = false;
      try {
        hypre_on_host = getHypreOnHostRequest(argc, argv).requested;
      } catch (...) {
        MPI_Finalize();
        throw;
      }
      if (hypre_on_host) {
        mfem::Hypre::configure_runtime_policy_from_mfem = false;
      }
      mfem::Hypre::Init();
      if (getMPIRankForDefaultCommunicator() != 0) {
        mfem::out.Disable();
        mfem::err.Disable();
      }
      Finalizer::get().initialize(argc, argv);
      first = false;
    }
  }  // end of initialize

#else /* MFEM_USE_MPI */

  void initialize(int& argc, MainFunctionArguments& argv) {
    static bool first = true;
    if (first) {
      internals::readExecutionSettings(argc, argv);
      internals::readSolverOverrides(argc, argv);
      Finalizer::get().initialize(argc, argv);
      first = false;
    }
  }  // end of initialize

