  int getMPISizeForDefaultCommunicator() noexcept {
    int size = 1;
#ifdef MFEM_USE_MPI
    MPI_Comm_size(MPI_COMM_WORLD, &size);
#endif /* MFEM_USE_MPI */
    return size;
  }  // end of getMPISizeForDefaultCommunicator

