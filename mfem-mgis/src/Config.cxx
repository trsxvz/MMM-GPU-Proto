  void Finalizer::finalize() {
#ifdef MFEM_MGIS_HAVE_KOKKOS
    // Kokkos is finalized before MPI, if it was initialized by mfem-mgis
    if (this->kokkos) {
      internals::finalizeKokkos();
      this->kokkos = false;
    }
#endif /* MFEM_MGIS_HAVE_KOKKOS */
    if (!this->pendingExit) {
#ifdef MFEM_USE_MPI
      this->finalizePETSc();
      mfem::Hypre::Finalize();
      MPI_Finalize();
      this->pendingExit = true;
#endif /* MFEM_USE_MPI */
    }
  }  // end of finalize

  [[noreturn]] void Finalizer::abort(int error) {
    // MPI_Abort does not flush the output streams
    mfem_mgis::getOutputStream().flush();
    mfem_mgis::getErrorStream().flush();
    if (!this->pendingExit) {
#ifdef MFEM_USE_MPI
      MPI_Abort(MPI_COMM_WORLD, error);
      this->pendingExit = true;
#endif /* MFEM_USE_MPI */
    }
    std::exit(error);
  }  // end of abort

