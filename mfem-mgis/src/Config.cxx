  /*!
   * \brief sets the size of the pool of memory allocated at once by hypre
   * on the GPU through Umpire (4 GiB by default in hypre 3.2), before the
   * first allocation of hypre on the GPU, which creates the pool. Each
   * process has its own pool.
   * \param[in] size: size in GiB, as given by the user
   * \param[in] environment: if true, the size is given by the environment
   * variable `MFEM_MGIS_HYPRE_DEVICE_POOL_SIZE`, ignored with a warning if
   * hypre does not use Umpire on the GPU (as for a whole test suite)
   */
  static void setHypreDevicePoolSize(const char* const size,
                                     const bool environment) {
    auto* end = static_cast<char*>(nullptr);
    const auto s = std::strtod(size, &end);
    // number of bytes, which must be representable
    const auto bytes = s * 1073741824.;
    if ((end == size) || (*end != '\0') || (!std::isfinite(s)) ||
        (!(bytes >= 1)) ||
        (!(bytes <
           static_cast<double>(std::numeric_limits<std::size_t>::max())))) {
      mgis::raise("initialize: invalid size of the pool of memory of hypre '" +
                  std::string{size} +
                  "' (strictly positive number of GiB expected)");
    }
#if defined(MFEM_USE_MPI) && defined(HYPRE_USING_UMPIRE_DEVICE)
    static_cast<void>(environment);
    // the function only stores the size: its result, the global error flag
    // of hypre, may report a previous error
    static_cast<void>(
        HYPRE_SetUmpireDevicePoolSize(static_cast<std::size_t>(bytes)));
#else
    if (!environment) {
      mgis::raise(
          "initialize: hypre does not use a pool of memory of Umpire on the "
          "GPU");
    }
    mfem_mgis::getErrorStream()
        << "initialize: hypre does not use a pool of memory of Umpire on the "
           "GPU, the variable MFEM_MGIS_HYPRE_DEVICE_POOL_SIZE is ignored\n";
#endif
  }  // end of setHypreDevicePoolSize

  //! \brief request of the computations of hypre on the host
  struct HypreOnHostRequest {
    //! \brief if true, hypre shall compute on the host
    bool requested = false;
    //! \brief if true, the request is given by the environment
    bool from_environment = false;
  };

  /*!
   * \return the request of the computations of hypre on the host, given by
   * the options `--hypre-on-host` and `--no-hypre-on-host` (the last one
   * prevails) or else by the environment variable `MFEM_MGIS_HYPRE_ON_HOST`,
   * or, in the `gpu` and `mixed` execution modes, by the location of the
   * linear solvers (see `ExecutionSettings`), which those options can't
   * contradict (the environment variable is then ignored)
   * \param[in] argc: number of arguments
   * \param[in] argv: arguments
   */
  static HypreOnHostRequest getHypreOnHostRequest(
      const int argc, const MainFunctionArguments argv) {
    // computed once, the request being read twice by `initialize`
    static auto request = std::optional<HypreOnHostRequest>{};
    if (request.has_value()) {
      return *request;
    }
    auto r = std::optional<bool>{};
    for (auto a = argv; a != argv + argc; ++a) {
      if ((std::strcmp(*a, Finalizer::hypre_on_host_option) == 0) ||
          (std::strcmp(*a, Finalizer::hypre_on_host_short_option) == 0)) {
        r = true;
      }
      if ((std::strcmp(*a, Finalizer::no_hypre_on_host_option) == 0) ||
          (std::strcmp(*a, Finalizer::no_hypre_on_host_short_option) == 0)) {
        r = false;
      }
    }
    const auto& s = getExecutionSettings();
    if ((s.mode == ExecutionMode::GPU) || (s.mode == ExecutionMode::MIXED)) {
      const auto on_host = s.linear_solver == ExecutionLocation::CPU;
      // the environment variable is ignored (with a warning)
      static_cast<void>(internals::getPlacementEnvironmentVariable(
          "MFEM_MGIS_HYPRE_ON_HOST"));
      if ((r.has_value()) && (*r != on_host)) {
        mgis::raise(
            "initialize: the option '" +
            std::string{*r ? Finalizer::hypre_on_host_option
                           : Finalizer::no_hypre_on_host_option} +
            "' contradicts the location of the linear solvers given by the "
            "execution settings");
      }
      request =
          HypreOnHostRequest{.requested = on_host, .from_environment = false};
    } else if (r.has_value()) {
      request = HypreOnHostRequest{.requested = *r, .from_environment = false};
    } else {
      const auto* const e =
          internals::getPlacementEnvironmentVariable("MFEM_MGIS_HYPRE_ON_HOST");
      const auto requested =
          (e != nullptr) && (*e != '\0') && (std::string_view{e} != "0");
      request = HypreOnHostRequest{.requested = requested,
                                   .from_environment = requested};
    }
    return *request;
  }  // end of getHypreOnHostRequest

  /*!
   * \brief makes hypre allocate its memory and compute on the host, after
   * the configuration of the device of MFEM. MFEM then gives the data of
   * hypre on the host (`mfem::HypreUsingGPU` is false), and the other
   * computations of MFEM and of mfem-mgis stay on the device.
   * \param[in] environment: if true, the request is given by the
   * environment, and is ignored with a warning if hypre can't compute on
   * the host at run time
   */
  static void setHypreOnHost([[maybe_unused]] const bool environment) {
#if defined(MFEM_USE_MPI) && defined(HYPRE_USING_GPU)
#if MFEM_HYPRE_VERSION >= 23100
    // the functions only store the policy: their results, the global error
    // flag of hypre, may report a previous error
    static_cast<void>(HYPRE_SetMemoryLocation(HYPRE_MEMORY_HOST));
    static_cast<void>(HYPRE_SetExecutionPolicy(HYPRE_EXEC_HOST));
#else  /* MFEM_HYPRE_VERSION >= 23100 */
    constexpr auto message =
        "initialize: hypre can't compute on the host when it is built with "
        "GPU support and older than 2.31.0";
    if (!environment) {
      mgis::raise(message);
    }
    mfem_mgis::getErrorStream()
        << message << ", the variable MFEM_MGIS_HYPRE_ON_HOST is ignored\n";
#endif /* MFEM_HYPRE_VERSION >= 23100 */
#endif /* defined(MFEM_USE_MPI) && defined(HYPRE_USING_GPU) */
  }  // end of setHypreOnHost

  /*!
   * \return true if a configuration of the device of MFEM uses a GPU
   * (`cuda`, `hip`, `gpu` and their variants `ceed-cuda`, `raja-gpu`, ...)
   * \param[in] configuration: configuration of the device
   */
  static bool usesGPU(const char* const configuration) {
    const auto c = std::string_view{configuration};
    return (c.find("cuda") != std::string_view::npos) ||
           (c.find("hip") != std::string_view::npos) ||
           (c.find("gpu") != std::string_view::npos);
  }  // end of usesGPU

  /*!
   * \brief sets the memory types of MFEM before the configuration of its
   * device, unless they are given by the environment (variable
   * `MFEM_MEMORY`, with which MFEM would ignore this call anyway): the
   * standard memory of the host, and the default memory of the device
   * (Umpire if MFEM is compiled with it). MFEM compiled with Umpire
   * otherwise allocates the memory of the host with Umpire too, which
   * records each allocation, including the temporaries of the loops over the
   * elements made on the host: post-processings, assemblies on the host and
   * exports were about five times slower.
   * \param[in] configuration: configuration of the device
   */
  static void setMemoryTypes(const char* const configuration) {
    if (std::getenv("MFEM_MEMORY") != nullptr) {
      return;
    }
    if (!usesGPU(configuration)) {
      mfem::Device::SetMemoryTypes(mfem::MemoryType::HOST,
                                   mfem::MemoryType::HOST);
      return;
    }
#ifdef MFEM_USE_UMPIRE
    mfem::Device::SetMemoryTypes(mfem::MemoryType::HOST,
                                 mfem::MemoryType::DEVICE_UMPIRE);
#else  /* MFEM_USE_UMPIRE */
    mfem::Device::SetMemoryTypes(mfem::MemoryType::HOST,
                                 mfem::MemoryType::DEVICE);
#endif /* MFEM_USE_UMPIRE */
  }  // end of setMemoryTypes

  /*!
   * \return the identifier of the GPU used by this process: the processes
   * of a node use the GPUs of the node in turn (several processes may share
   * a GPU)
   * \param[in] configuration: configuration of the device
   */
  static int getDeviceIdentifier(const char* const configuration) {
#if defined(MFEM_USE_CUDA) || defined(MFEM_USE_HIP)
    // MFEM aborts if the number of GPUs is queried on a machine without GPU:
    // it is only queried for a configuration using a GPU
    if (!usesGPU(configuration)) {
      return 0;
    }
    const auto n = mfem::Device::GetDeviceCount();
    if (n <= 0) {
      return 0;
    }
#ifdef MFEM_USE_MPI
    auto local = MPI_Comm{};
    MPI_Comm_split_type(MPI_COMM_WORLD, MPI_COMM_TYPE_SHARED, 0, MPI_INFO_NULL,
                        &local);
    auto r = int{};
    MPI_Comm_rank(local, &r);
    MPI_Comm_free(&local);
    return r % n;
#else  /* MFEM_USE_MPI */
    return 0;
#endif /* MFEM_USE_MPI */
#else  /* defined(MFEM_USE_CUDA) || defined(MFEM_USE_HIP) */
    // without GPU support, MFEM aborts if the number of GPUs is queried
    static_cast<void>(configuration);
    return 0;
#endif /* defined(MFEM_USE_CUDA) || defined(MFEM_USE_HIP) */
  }  // end of getDeviceIdentifier

  /*!
   * \brief creates the allocators of Umpire of the device memory types of
   * MFEM on the given GPU, before the configuration of the device of MFEM,
   * unless they exist. MFEM 4.10 creates them on the resource `DEVICE` of
   * Umpire, which is the GPU 0, whatever the GPU of the device
   * (mfem/mfem#5696): MFEM uses these allocators instead, which have the
   * names it looks for. Nothing is done for the GPU 0.
   * \param[in] gpu: identifier of the GPU of the device of MFEM
   */
  static void createUmpireDeviceAllocators([[maybe_unused]] const int gpu) {
#if defined(MFEM_USE_UMPIRE) && \
    (defined(MFEM_USE_CUDA) || defined(MFEM_USE_HIP))
    if (gpu == 0) {
      return;
    }
    auto& rm = umpire::ResourceManager::getInstance();
    const auto resource = "DEVICE::" + std::to_string(gpu);
    for (const auto* const name :
         {mfem::MemoryManager::GetUmpireDeviceAllocatorName(),
          mfem::MemoryManager::GetUmpireDevice2AllocatorName()}) {
      if (!rm.isAllocator(name)) {
        static_cast<void>(rm.makeAllocator<umpire::strategy::QuickPool>(
            name, rm.getAllocator(resource)));
      }
    }
#endif
  }  // end of createUmpireDeviceAllocators

#ifdef MFEM_USE_MPI
  /*!
   * \return false if the MPI library states that it can't read the memory of
   * the GPUs (extensions of Open MPI), true otherwise
   */
  static bool mayMPIReadGPUMemory() {
#if defined(MFEM_USE_CUDA) && defined(MPIX_CUDA_AWARE_SUPPORT)
    return MPIX_Query_cuda_support() == 1;
#elif defined(MFEM_USE_HIP) && defined(MPIX_ROCM_AWARE_SUPPORT)
    return MPIX_Query_rocm_support() == 1;
#else
    // unknown
    return true;
#endif
  }  // end of mayMPIReadGPUMemory
#endif /* MFEM_USE_MPI */

  /*!
   * \brief makes MFEM, hypre (if it computes on the GPU) and AmgX give the
   * arrays on the GPU to MPI, without copies on the host, after the
   * configuration of the device of MFEM and of the memory of hypre
   * \param[in] environment: if true, the request is given by the
   * environment, and is ignored with a warning if it can't be satisfied
   */
  static void setGPUAwareMPI(const bool environment) {
    const auto refuse = [environment](const std::string& reason) {
      const auto message = "initialize: GPU-aware MPI " + reason;
      if (!environment) {
        mgis::raise(message);
      }
      mfem_mgis::getErrorStream()
          << message << ", the variable MFEM_MGIS_GPU_AWARE_MPI is ignored\n";
    };
#ifdef MFEM_USE_MPI
    if ((!mfem::Device::IsConfigured()) ||
        (!mfem::Device::Allows(mfem::Backend::CUDA_MASK |
                               mfem::Backend::HIP_MASK))) {
      refuse("requires a device of MFEM using a GPU");
      return;
    }
    if (!mayMPIReadGPUMemory()) {
      refuse("is not supported by the MPI library");
      return;
    }
    // read by AmgX at the creation of its resources (see `AmgXSolvers.cxx`)
    mfem::Device::SetGPUAwareMPI(true);
#ifdef HYPRE_USING_GPU
    if (mfem::HypreUsingGPU()) {
      // the function only stores the choice: its result, the global error
      // flag of hypre, may report a previous error
      static_cast<void>(HYPRE_SetGpuAwareMPI(1));
    }
#endif /* HYPRE_USING_GPU */
#else  /* MFEM_USE_MPI */
    refuse("requires mfem-mgis built with MPI");
#endif /* MFEM_USE_MPI */
  }  // end of setGPUAwareMPI

  /*!
   * \brief waits for the end of the kernels launched on the GPU, so that
   * their duration is counted in the profiling section which launched them
   */
  static void synchronizeDevice() noexcept {
#if defined(MFEM_USE_CUDA) || defined(MFEM_USE_HIP)
    try {
      MFEM_DEVICE_SYNC;
    } catch (...) {
      // an error of the GPU is reported by the next call to the GPU
    }
#endif /* defined(MFEM_USE_CUDA) || defined(MFEM_USE_HIP) */
  }  // end of synchronizeDevice

  Finalizer::Finalizer() = default;

#ifdef MFEM_MGIS_HAVE_PETSC
  void Finalizer::setPETSc(const char* petscrc_file) {
    this->use_petsc = true;
    mfem::MFEMInitializePetsc(nullptr, nullptr, petscrc_file, nullptr);
  }
  void Finalizer::initializePETScOnDemand() {
    // PETSc is already initialized when its non linear solver is used
    if ((this->use_petsc) || (this->petsc_initialized_on_demand)) {
      return;
    }
    mfem::MFEMInitializePetsc();
    this->petsc_initialized_on_demand = true;
  }  // end of initializePETScOnDemand

  void Finalizer::finalizePETSc() {
    if ((this->pendingExit) || (this->petsc_finalized) ||
        ((!this->use_petsc) && (!this->petsc_initialized_on_demand))) {
      return;
    }
    mfem::MFEMFinalizePetsc();
    this->petsc_finalized = true;
  }  // end of finalizePETSc
#else  /* MFEM_MGIS_HAVE_PETSC */
  void Finalizer::setPETSc(const char*) {
    mgis::raise("Finalizer::setPETSc: PETSc is not supported");
  }

  void Finalizer::initializePETScOnDemand() {
    mgis::raise("Finalizer::initializePETScOnDemand: PETSc is not supported");
  }

  void Finalizer::finalizePETSc() {}
#endif /*MFEM_MGIS_HAVE_PETSC*/

  void Finalizer::initializeKokkosOnDemand() {
#ifdef MFEM_MGIS_HAVE_KOKKOS
    if (internals::isKokkosInitialized()) {
      return;
    }
    // the GPU of the device of MFEM, as in `initialize`
    auto gpu = -1;
    if (mfem::Device::IsConfigured() &&
        mfem::Device::Allows(mfem::Backend::CUDA_MASK |
                             mfem::Backend::HIP_MASK)) {
      gpu = mfem::Device::GetId();
    }
    if (internals::initializeKokkos(gpu)) {
      this->kokkos = true;
    }
#else  /* MFEM_MGIS_HAVE_KOKKOS */
    mgis::raise(
        "Finalizer::initializeKokkosOnDemand: mfem-mgis is built without "
        "Kokkos (option enable-kokkos)");
#endif /* MFEM_MGIS_HAVE_KOKKOS */
  }  // end of initializeKokkosOnDemand

  void Finalizer::initialize(int& argc, MainFunctionArguments& argv) {
#ifdef MFEM_MGIS_HAVE_PETSC
    const char* petscrc_file = nullptr;
#endif /* MFEM_MGIS_HAVE_PETSC */
    const char* device_configuration = nullptr;
    const char* hypre_device_pool_size = nullptr;
    auto hypre_device_pool_size_from_environment = false;
    // initialization of Kokkos, requested by the option or by the
    // environment
    auto kokkos_requested = std::optional<bool>{};
    // GPU-aware MPI, requested by the option or by the environment
    auto gpu_aware_mpi_requested = std::optional<bool>{};
    for (const auto* a = argv; a != argv + argc; ++a) {
      if ((std::strcmp(*a, kokkos_option) == 0) ||
          (std::strcmp(*a, kokkos_short_option) == 0)) {
        kokkos_requested = true;
        continue;
      }
      if ((std::strcmp(*a, no_kokkos_option) == 0) ||
          (std::strcmp(*a, no_kokkos_short_option) == 0)) {
        kokkos_requested = false;
        continue;
      }
      if ((std::strcmp(*a, gpu_aware_mpi_option) == 0) ||
          (std::strcmp(*a, gpu_aware_mpi_short_option) == 0)) {
        gpu_aware_mpi_requested = true;
        continue;
      }
      if ((std::strcmp(*a, no_gpu_aware_mpi_option) == 0) ||
          (std::strcmp(*a, no_gpu_aware_mpi_short_option) == 0)) {
        gpu_aware_mpi_requested = false;
        continue;
      }
      if ((std::strcmp(*a, hypre_device_pool_size_option) == 0) ||
          (std::strcmp(*a, hypre_device_pool_size_short_option) == 0)) {
        if (hypre_device_pool_size != nullptr) {
          mgis::raise(
              "initialize: size of the pool of memory of hypre already "
              "specified");
        }
        ++a;
        if (a == argv + argc) {
          mgis::raise("initialize: no value given to " +
                      std::string{hypre_device_pool_size_option});
        }
        hypre_device_pool_size = *a;
        continue;
      }
      if ((std::strcmp(*a, device_option) == 0) ||
          (std::strcmp(*a, device_short_option) == 0)) {
        if (device_configuration != nullptr) {
          mgis::raise("initialize: MFEM device already specified");
        }
        ++a;
        if (a == argv + argc) {
          mgis::raise("initialize: no value given to --device");
        }
        device_configuration = *a;
        continue;
      }
#ifdef MFEM_MGIS_HAVE_PETSC
      // long and short names, as declared by `declareDefaultOptions`
      if ((std::strcmp(*a, "--use-petsc") == 0) ||
          (std::strcmp(*a, "-up") == 0)) {
        this->use_petsc = true;
      }
      if ((std::strcmp(*a, "--donot-use-petsc") == 0) ||
          (std::strcmp(*a, "-no-up") == 0)) {
        this->use_petsc = false;
      }
      if ((std::strcmp(*a, petsc_configuration_file_option) == 0) ||
          (std::strcmp(*a, "petscrc_file") == 0)) {
        if (petscrc_file != nullptr) {
          mgis::raise("initialize: PETSc configuration file already specified");
        }
        ++a;
        if (a == argv + argc) {
          mgis::raise(
              "initialize: no value given to --petsc-configuration-file");
        }
        petscrc_file = *a;
      }
#endif /* MFEM_MGIS_HAVE_PETSC */
    }
    // size of the pool of memory of hypre on the GPU, given by the option or
    // by the environment
    if (hypre_device_pool_size == nullptr) {
      const auto* const e = std::getenv("MFEM_MGIS_HYPRE_DEVICE_POOL_SIZE");
      if ((e != nullptr) && (*e != '\0')) {
        hypre_device_pool_size = e;
        hypre_device_pool_size_from_environment = true;
      }
    }
    // hypre on the host, requested by the option or by the environment
    // (see also `initialize`, which reads the same request before the
    // initialization of hypre)
    const auto hypre_on_host_request = getHypreOnHostRequest(argc, argv);
    const auto hypre_on_host = hypre_on_host_request.requested;
    // contradictions between the options, reported before the checks
    // depending on the build of hypre
    const auto& execution = getExecutionSettings();
    if ((execution.mode == ExecutionMode::CPU) &&
        (hypre_device_pool_size != nullptr) &&
        (!hypre_device_pool_size_from_environment)) {
      mgis::raise(
          "initialize: the size of the pool of memory of hypre on the GPU "
          "can't be given with '--execution cpu'");
    }
    if (hypre_device_pool_size != nullptr) {
      if (hypre_on_host && (!hypre_device_pool_size_from_environment)) {
        mgis::raise(
            "initialize: the size of the pool of memory of hypre on the GPU "
            "can't be given when hypre computes on the host");
      }
      setHypreDevicePoolSize(hypre_device_pool_size,
                             hypre_device_pool_size_from_environment);
    }
    // without the option, the configuration of the device may be given by
    // the environment, for instance to run a whole test suite on a GPU
    if (device_configuration == nullptr) {
      const auto* const e =
          internals::getPlacementEnvironmentVariable("MFEM_MGIS_DEVICE");
      if ((e != nullptr) && (*e != '\0') && (!mfem::Device::IsConfigured())) {
        device_configuration = e;
      }
    }
#ifdef MFEM_MGIS_HAVE_PETSC
    // PETSc solves the non linear problems on the host
    if ((this->use_petsc) && (execution.mode != ExecutionMode::UNSPECIFIED) &&
        (execution.linear_solver == ExecutionLocation::GPU)) {
      mgis::raise(
          "initialize: PETSc computes on the CPU, while the execution "
          "settings place the linear solvers on the GPU (use '--execution "
          "cpu' or '--execution mixed --linear-solvers-execution cpu')");
    }
#endif /* MFEM_MGIS_HAVE_PETSC */
    // execution settings: no GPU in the cpu mode, the `gpu` device of MFEM
    // (CUDA or HIP, as MFEM is built) by default in the gpu and mixed modes
    if (execution.mode == ExecutionMode::CPU) {
      if ((device_configuration != nullptr) &&
          (usesGPU(device_configuration))) {
        mgis::raise("initialize: the device '" +
                    std::string{device_configuration} +
                    "' uses a GPU, which contradicts '--execution cpu'");
      }
      if ((mfem::Device::IsConfigured()) &&
          (mfem::Device::Allows(mfem::Backend::CUDA_MASK |
                                mfem::Backend::HIP_MASK))) {
        mgis::raise(
            "initialize: the device of MFEM, configured before the "
            "initialization (by the program or by the variable MFEM_DEVICE), "
            "uses a GPU, which contradicts '--execution cpu'");
      }
    } else if (execution.mode != ExecutionMode::UNSPECIFIED) {
      if ((device_configuration == nullptr) &&
          (!mfem::Device::IsConfigured())) {
        device_configuration = "gpu";
      }
      if ((device_configuration != nullptr) &&
          (!usesGPU(device_configuration))) {
        mgis::raise("initialize: the device '" +
                    std::string{device_configuration} +
                    "' does not use a GPU, which the execution mode requires");
      }
      if ((device_configuration == nullptr) &&
          (!mfem::Device::Allows(mfem::Backend::CUDA_MASK |
                                 mfem::Backend::HIP_MASK))) {
        mgis::raise(
            "initialize: the device of MFEM, configured before the "
            "initialization (by the program or by the variable MFEM_DEVICE), "
            "does not use a GPU, which the execution mode requires");
      }
    }
    // the device is configured after the initialization of hypre and
    // before the one of PETSc, which uses the GPU of the device, as in the
    // parallel examples of MFEM
    // identifier of the GPU of the device of MFEM, given to Kokkos, -1 if
    // the device does not use a GPU
    auto gpu_identifier = -1;
    if (device_configuration != nullptr) {
      if (mfem::Device::IsConfigured()) {
        mgis::raise(
            "initialize: the MFEM device is already configured, the "
            "option '--device' can't be used");
      }
      const auto identifier = getDeviceIdentifier(device_configuration);
      setMemoryTypes(device_configuration);
      if (usesGPU(device_configuration)) {
        createUmpireDeviceAllocators(identifier);
      }
      this->device =
          std::make_unique<mfem::Device>(device_configuration, identifier);
      // the kernels are launched asynchronously on a GPU: the profiling
      // sections wait for them
      if (mfem::Device::Allows(mfem::Backend::CUDA_MASK |
                               mfem::Backend::HIP_MASK)) {
        mgis::setProfilingSynchronization(&synchronizeDevice);
        gpu_identifier = identifier;
      }
    }
    // hypre on the host, after the configuration of the device by this
    // function, by the program or by the variable MFEM_DEVICE of MFEM: the
    // policy must be set, hypre built with GPU support computing on the GPU
    // by default
    if (hypre_on_host) {
      setHypreOnHost(hypre_on_host_request.from_environment);
    }
    // GPU-aware MPI, after the configuration of the device and of the
    // memory of hypre; requested by the option or by the environment
    auto gpu_aware_mpi_from_environment = false;
    if (!gpu_aware_mpi_requested.has_value()) {
      const auto* const e = std::getenv("MFEM_MGIS_GPU_AWARE_MPI");
      gpu_aware_mpi_requested =
          (e != nullptr) && (*e != '\0') && (std::string_view{e} != "0");
      gpu_aware_mpi_from_environment = *gpu_aware_mpi_requested;
    }
    if (*gpu_aware_mpi_requested) {
      setGPUAwareMPI(gpu_aware_mpi_from_environment);
    }
    // Kokkos, after the device of MFEM, whose GPU it uses; requested by the
    // option or by the environment
    auto kokkos_from_environment = false;
    if (!kokkos_requested.has_value()) {
      const auto* const e = std::getenv("MFEM_MGIS_KOKKOS");
      kokkos_requested =
          (e != nullptr) && (*e != '\0') && (std::string_view{e} != "0");
      kokkos_from_environment = *kokkos_requested;
    }
    if (*kokkos_requested) {
#ifdef MFEM_MGIS_HAVE_KOKKOS
      static_cast<void>(kokkos_from_environment);
      if ((gpu_identifier < 0) && mfem::Device::IsConfigured() &&
          mfem::Device::Allows(mfem::Backend::CUDA_MASK |
                               mfem::Backend::HIP_MASK)) {
        // device configured by the program before the initialization
        gpu_identifier = mfem::Device::GetId();
      }
      this->kokkos = internals::initializeKokkos(gpu_identifier);
#else  /* MFEM_MGIS_HAVE_KOKKOS */
      static_cast<void>(gpu_identifier);
      if (!kokkos_from_environment) {
        mgis::raise(
            "initialize: mfem-mgis is built without Kokkos (option "
            "enable-kokkos), which can't be initialized");
      }
      // the variable may be given to a whole test suite
      mfem_mgis::getErrorStream()
          << "initialize: mfem-mgis is built without Kokkos (option "
             "enable-kokkos), the variable MFEM_MGIS_KOKKOS is ignored\n";
#endif /* MFEM_MGIS_HAVE_KOKKOS */
    }
    // an invalid choice of the computation of the post-processings is
    // reported here rather than at the first post-processing (the variable
    // is read again at each computation)
    static_cast<void>(internals::usePostProcessingsKernels(may_throw));
#ifdef MFEM_MGIS_HAVE_PETSC
    if (this->use_petsc) {
      if (petscrc_file == nullptr) {
        mgis::raise("initialize: no PETSc configuration file given");
      }
      mfem::MFEMInitializePetsc(nullptr, nullptr, petscrc_file, nullptr);
    }
#endif /* MFEM_MGIS_HAVE_PETSC */
  }    // end of initialize

