/*!
 * \brief failure of the integration at some points: the strain varies
 * along the x axis (displacement a x^2), the behaviour fails where the
 * trace of the strain exceeds a threshold. The integration fails in both
 * modes. By batches, MGIS integrates the points of a behaviour generated by
 * the generic interface one by one up to the first failure, and all the
 * points of a behaviour generated by the generic-parallel interface: the
 * thermodynamic forces are checked where they are computed.
 * \param[in] mode: value of the `BehaviourIntegration` parameter
 * \param[in] all_points: if true, all the points are integrated
 */
static void testFailure(mfem_mgis::Context& ctx,
                        const char* const mesh,
                        const char* const library,
                        const char* const mode,
                        const bool all_points) {
  using namespace mfem_mgis;
  auto or_die = ctx.getFatalFailureHandler();
  auto problem = construct<NonLinearEvolutionProblem>(
                     ctx, Parameters{{"MeshFileName", mesh},
                                     {"FiniteElementFamily", "H1"},
                                     {"FiniteElementOrder", 1},
                                     {"UnknownsSize", 3},
                                     {"NumberOfUniformRefinements", 2},
                                     {"Hypothesis", "Tridimensional"},
                                     {"BehaviourIntegration", mode},
                                     {"Parallel", false}}) |
                 or_die;
  problem.addBehaviourIntegrator(ctx, "Mechanics", 1, library,
                                 "FailingIsotropicLinearElasticity") |
      or_die;
  auto& m = problem.getMaterial(ctx, 1, 0) | or_die;
  for (auto* s : {&m.s0, &m.s1}) {
    mgis::behaviour::setExternalStateVariable(ctx, *s, "Temperature", 293.15) |
        or_die;
  }
  // the threshold of the trace of the strain is 1e-3: the integration
  // fails for x > 1/2
  auto& fespace =
      problem.getFiniteElementDiscretization().getFiniteElementSpace<false>();
  auto gf = mfem::GridFunction(&fespace);
  auto c = mfem::VectorFunctionCoefficient(
      3, [](const mfem::Vector& x, mfem::Vector& v) {
        v = 0.;
        v[0] = 1e-3 * x[0] * x[0];
      });
  gf.ProjectCoefficient(c);
  auto u = mfem::Vector{};
  gf.GetTrueDofs(u);
  const auto name = std::string{"failure ("} + mode +
                    (all_points ? ", generic-parallel" : "") + ")";
  check(!problem.integrate(
            u, IntegrationType::INTEGRATION_CONSISTENT_TANGENT_OPERATOR, 1),
        name + ": the failure of the integration is not reported");
  if (std::string_view{mode} != "Batch") {
    return;
  }
  // by batches, all the points are integrated: the stresses are the ones of
  // the elasticity where the integration succeeds
  m.synchronizeOnHostForReading();
  const auto gs = m.s1.gradients_stride;
  const auto ts = m.s1.thermodynamic_forces_stride;
  auto nsuccess = size_type{};
  auto nfailure = size_type{};
  auto ok = true;
  for (size_type i = 0; i != static_cast<size_type>(m.n); ++i) {
    const auto* const e = m.s1.gradients.data() + i * gs;
    const auto* const sig = m.s1.thermodynamic_forces.data() + i * ts;
    const auto tr = e[0] + e[1] + e[2];
    if (std::abs(tr) > 1e-3) {
      ++nfailure;
      continue;
    }
    if ((!all_points) && (nfailure != 0)) {
      // not integrated after the first failure
      continue;
    }
    ++nsuccess;
    const auto sxx = 1.2e11 * tr + 2 * 8e10 * e[0];
    ok = ok && (std::abs(sig[0] - sxx) <= 1e-8 * std::abs(sxx));
  }
  check((nsuccess != 0) && (nfailure != 0),
        name + ": the integration shall fail at some points only");
  check(ok, name + ": stresses where the integration succeeds");
}  // end of testFailure

/*!
 * \brief inner forces computed element by element just after the
 * integration of the behaviour on the element, as by the assembly of the
 * residual with PETSc (`MultiMaterialNonLinearIntegrator`): same values as
 * when all the elements are integrated before the computation of the inner
 * forces, for an orthotropic behaviour whose thermodynamic forces are
 * rotated in the global frame by the computation of the inner forces
 * \param[in] behaviour: behaviour
 */
static void testElementByElementSequence(mfem_mgis::Context& ctx,
                                         const char* const mesh,
                                         const char* const library,
                                         const std::string& behaviour) {
  using namespace mfem_mgis;
  auto or_die = ctx.getFatalFailureHandler();
  auto problem = construct<NonLinearEvolutionProblem>(
                     ctx, Parameters{{"MeshFileName", mesh},
                                     {"FiniteElementFamily", "H1"},
                                     {"FiniteElementOrder", 1},
                                     {"UnknownsSize", 3},
                                     {"NumberOfUniformRefinements", 1},
                                     {"Hypothesis", "Tridimensional"},
                                     {"Parallel", false}}) |
                 or_die;
  problem.addBehaviourIntegrator(ctx, "Mechanics", 1, library, behaviour) |
      or_die;
  auto& m = problem.getMaterial(ctx, 1, 0) | or_die;
  for (auto* s : {&m.s0, &m.s1}) {
    mgis::behaviour::setExternalStateVariable(ctx, *s, "Temperature", 293.15) |
        or_die;
  }
  const auto c = std::cos(0.3);
  const auto s = std::sin(0.3);
  m.setRotationMatrix(
      RotationMatrix3D{std::array<real, 9u>{c, s, 0, -s, c, 0, 0, 0, 1}});
  auto& bi = problem.getBehaviourIntegrator(ctx, 1, 0) | or_die;
  check(bi.setup(ctx, 0, 1), behaviour + ": setup");
  auto& fes =
      problem.getFiniteElementDiscretization().getFiniteElementSpace<false>();
  // a displacement field with a non uniform gradient
  auto displacement = [&fes](const real a) {
    auto gf = mfem::GridFunction(&fes);
    auto f = mfem::VectorFunctionCoefficient(
        3, [a](const mfem::Vector& x, mfem::Vector& v) {
          v[0] = a * (x[0] * x[0] + 0.3 * x[1]);
          v[1] = a * 0.5 * x[0] * x[2];
          v[2] = -a * 0.2 * x[1] * x[1];
        });
    gf.ProjectCoefficient(f);
    return mfem::Vector(gf);
  };
  using ElementsInnerForces = std::vector<std::vector<real>>;
  // inner forces, element by element: if `interleaved` is true, each
  // element is integrated just before the computation of its inner forces;
  // otherwise, all the elements are integrated first
  auto compute_inner_forces = [&](const mfem::Vector& u,
                                  const bool interleaved) {
    m.synchronizeOnHost();
    auto F = ElementsInnerForces{};
    auto vdofs = mfem::Array<int>{};
    auto ue = mfem::Vector{};
    auto Fe = mfem::Vector{};
    auto integrate = [&](const int i) {
      fes.GetElementVDofs(i, vdofs);
      u.GetSubVector(vdofs, ue);
      check(bi.integrate(
                *(fes.GetFE(i)), *(fes.GetElementTransformation(i)), ue,
                IntegrationType::INTEGRATION_CONSISTENT_TANGENT_OPERATOR),
            behaviour + ": integration");
    };
    if (!interleaved) {
      for (int i = 0; i != fes.GetNE(); ++i) {
        integrate(i);
      }
    }
    for (int i = 0; i != fes.GetNE(); ++i) {
      if (interleaved) {
        integrate(i);
      }
      bi.computeInnerForces(Fe, *(fes.GetFE(i)),
                            *(fes.GetElementTransformation(i)));
      F.emplace_back(Fe.GetData(), Fe.GetData() + Fe.Size());
    }
    return F;
  };
  // two successive residuals, as two iterations of a non linear solver
  for (const auto a : {1e-3, 2e-3}) {
    const auto u = displacement(a);
    const auto F1 = compute_inner_forces(u, true);
    const auto F2 = compute_inner_forces(u, false);
    check(F1 == F2, behaviour +
                        ": inner forces computed element by element just "
                        "after the integration of each element");
  }
}  // end of testElementByElementSequence

/*!
 * \brief the regularizations whose stiffness matrices (FBar) or inner forces
 * (Faltus et al.) depend on the current estimate of the solution can't be
 * computed by kernels from gradients computed element by element: the
 * resolution is refused at its setup (FBar: tangent operator assembled by
 * kernels or applied without assembly; Faltus et al.: inner forces)
 * \param[in, out] ctx: execution context
 * \param[in] mesh: mesh
 * \param[in] library: behaviour library
 */
static void testRegularizationRefusal(mfem_mgis::Context& ctx,
                                      const char* const mesh,
                                      const char* const library) {
  using namespace mfem_mgis;
  auto or_die = ctx.getFatalFailureHandler();
  const auto fbar = Parameters{{"FBar", Parameters{}}};
  const auto faltus =
      Parameters{{"Faltus2026", Parameters{{"PenalizationCoefficient", 1e10}}}};
  struct Configuration {
    //! \brief name of the configuration
    const char* name;
    //! \brief regularization
    Parameters regularization;
    //! \brief computation of the inner forces
    const char* inner_forces;
    //! \brief computation of the tangent operator
    const char* tangent;
  };
  for (const auto& c :
       {Configuration{"FBar, tangent operator assembled by kernels", fbar,
                      "ElementByElement", "Kernels"},
        Configuration{"FBar, tangent operator applied without assembly", fbar,
                      "ElementByElement", "MatrixFree"},
        Configuration{"Faltus, inner forces computed by kernels", faltus,
                      "Kernels", "ElementByElement"}}) {
    auto problem =
        construct<NonLinearEvolutionProblem>(
            ctx, Parameters{{"MeshFileName", mesh},
                            {"FiniteElementFamily", "H1"},
                            {"FiniteElementOrder", 1},
                            {"UnknownsSize", 3},
                            {"NumberOfUniformRefinements", 1},
                            {"Materials", Parameters{{"Cube", 1}}},
                            {"Boundaries", Parameters{{"Ymin", 1},
                                                      {"Zmin", 2},
                                                      {"Xmax", 3},
                                                      {"Xmin", 5}}},
                            {"Hypothesis", "Tridimensional"},
                            {"BehaviourIntegration", "Batch"},
                            {"GradientsComputation", "ElementByElement"},
                            {"InnerForcesComputation", c.inner_forces},
                            {"TangentOperatorComputation", c.tangent},
                            {"Parallel", parallel}}) |
        or_die;
    problem.addBehaviourIntegrator(ctx, "Mechanics", "Cube", library,
                                   "SaintVenantKirchhoffElasticity",
                                   {{"Regularization", c.regularization}}) |
        or_die;
    auto& m = problem.getMaterial(ctx, "Cube", 0) | or_die;
    for (auto* s : {&m.s0, &m.s1}) {
      mgis::behaviour::setExternalStateVariable(ctx, *s, "Temperature",
                                                293.15) |
          or_die;
    }
    for (const auto& [boundary, component] :
         {std::pair{"Xmin", 0}, std::pair{"Ymin", 1}, std::pair{"Zmin", 2}}) {
      problem.addUniformDirichletBoundaryCondition(
          ctx, {{"Boundary", boundary}, {"Component", component}}) |
          or_die;
    }
    problem.addUniformDirichletBoundaryCondition(
        ctx, {{"Boundary", "Xmax"},
              {"Component", 0},
              {"LoadingEvolution",
               [](const real t) noexcept { return 1e-2 * t; }}}) |
        or_die;
    if (std::string_view{c.tangent} == "MatrixFree") {
      problem.setLinearSolver(
          ctx, "CGSolver",
          {{"VerbosityLevel", 0},
           {"RelativeTolerance", 1e-14},
           {"AbsoluteTolerance", 0.},
           {"MaximumNumberOfIterations", 1000},
           {"Preconditioner",
            Parameters{{"Name", "OperatorJacobiSmoother"}}}}) |
          or_die;
    } else {
      problem.setLinearSolver(ctx, parallel ? "MUMPSSolver" : "UMFPackSolver",
                              {}) |
          or_die;
    }
    problem.setSolverParameters(ctx, {{"VerbosityLevel", 0},
                                      {"RelativeTolerance", 1e-12},
                                      {"AbsoluteTolerance", 0.},
                                      {"MaximumNumberOfIterations", 10}}) |
        or_die;
    auto ctx2 = Context{};
    const auto r = problem.solve(ctx2, 0, 1);
    const auto msg = std::string{ctx2.getErrorMessage()};
    check((!r.status) &&
              (msg.find("gradients computed by kernels") != std::string::npos),
          std::string{c.name} +
              ", from gradients computed element by element: accepted (" + msg +
              ")");
  }
}  // end of testRegularizationRefusal

