/*!
 * \file   HeatTransferKernelsTest.cxx
 * \brief  Test of the computations by kernels of the stationary non linear
 * heat transfer behaviours (temperature gradient, heat flux, temperature as
 * external state variable computed from the unknowns): the integration by
 * batches with the gradients, the inner forces and the tangent operator
 * computed by kernels (assembled, or applied without assembly), with or
 * without elastic prediction, gives the results of the integration point by
 * point, in 3D, in plane strain and in plane stress, for an isotropic and a
 * rotated orthotropic behaviour, and for two materials, with temperatures
 * imposed on three sides (the temperature depends on all the coordinates),
 * for the behaviours generated by the generic interface and, if given, by
 * the generic-parallel interface.
 * \date   10/10/2026
 */

#include <array>
#include <cmath>
#include <span>
#include <string>
#include <vector>
#include <string_view>
#include <cstdlib>
#include <iostream>
#include <algorithm>
#include "mfem/general/optparser.hpp"
#include "MFEMMGIS/Config.hxx"
#include "MFEMMGIS/Parameters.hxx"
#include "MFEMMGIS/Material.hxx"
#include "MFEMMGIS/RotationMatrix.hxx"
#include "MFEMMGIS/NonLinearEvolutionProblem.hxx"

//! \brief number of failed checks
static int failures = 0;
//! \brief if true, the computations are parallel
static bool parallel = false;

static void check(const bool b, const std::string& msg) {
  if (!b) {
    std::cerr << "check failed: " << msg << '\n';
    ++failures;
  }
}  // end of check

//! \brief behaviour of a material
struct MaterialDescription {
  //! \brief library
  const char* library = "";
  //! \brief name of the behaviour
  const char* behaviour = "StationaryNonLinearHeatTransfer";
};

//! \brief problem
struct Case {
  //! \brief name
  std::string name;
  //! \brief modelling hypothesis
  const char* hypothesis = "Tridimensional";
  //! \brief mesh: a cube with one or two materials, or a unit square
  const char* mesh = "";
  //! \brief behaviours of the materials (one or two)
  std::vector<MaterialDescription> materials;
  /*!
   * \brief if true, the transient term of the heat equation is added to each
   * material (behaviour integrator `TransientHeatTransfer`, behaviour
   * `HeatStorage`)
   */
  bool transient = false;
};

//! \brief options of a computation
struct ComputationOptions {
  //! \brief integration of the behaviour: `PointByPoint` or `Batch`
  const char* integration = "PointByPoint";
  //! \brief if true, the gradients, inner forces and tangent are kernels
  bool kernels = false;
  //! \brief if true, the tangent operator is applied without assembly
  bool matrix_free = false;
  //! \brief if true, an elastic prediction is made at each time step
  bool prediction = false;
};

//! \brief results of a computation
struct Results {
  //! \brief status
  bool status = false;
  //! \brief temperature at the nodes at the end of the computation
  std::vector<mfem_mgis::real> u;
  //! \brief heat flux at the integration points
  std::vector<mfem_mgis::real> flux;
  //! \brief temperature at the integration points
  std::vector<mfem_mgis::real> temperature;
  //! \brief number of Newton iterations of each time step
  std::vector<int> iterations;
};

/*!
 * \brief sets the material axes of an orthotropic behaviour: a rotation
 * which is not a symmetry of the material, nor its own inverse, around the
 * z axis in 2D, around the z axis then the x axis in 3D, different for each
 * material
 * \param[in] m: material
 * \param[in] tridimensional: if true, the computation is 3D
 * \param[in] i: index of the material
 */
static void setMaterialAxes(mfem_mgis::Material& m,
                            const bool tridimensional,
                            const int i) {
  using namespace mfem_mgis;
  const auto a = 0.3 + 0.2 * i;
  const auto b = tridimensional ? 0.5 : 0.;
  const auto ca = std::cos(a);
  const auto sa = std::sin(a);
  const auto cb = std::cos(b);
  const auto sb = std::sin(b);
  // columns of Rz(a) Rx(b)
  const auto r = std::array<real, 9u>{ca, sa,      0,        -sa * cb, ca * cb,
                                      sb, sa * sb, -ca * sb, cb};
  if (tridimensional) {
    m.setRotationMatrix(RotationMatrix3D{r});
  } else {
    m.setRotationMatrix(RotationMatrix2D{r});
  }
}  // end of setMaterialAxes

/*!
 * \return the results of the computation
 * \param[in] c: problem
 * \param[in] opts: options
 */
static Results compute(const Case& c, const ComputationOptions& opts) {
  using namespace mfem_mgis;
  auto ctx = Context{};
  auto or_die = ctx.getFatalFailureHandler();
  const auto* const kernels = opts.kernels ? "Kernels" : "ElementByElement";
  const auto* const tangent = opts.matrix_free ? "MatrixFree" : kernels;
  const auto tridimensional =
      std::string_view{c.hypothesis} == "Tridimensional";
  // boundaries: x = 0 (5), x = 1 (3) and y = 1 (4) of the cubes, x = 0 (2),
  // x = 1 (4) and y = 1 (3) of the unit square
  const auto xmin = tridimensional ? 5 : 2;
  const auto xmax = tridimensional ? 3 : 4;
  const auto ymax = tridimensional ? 4 : 3;
  auto materials = Parameters{};
  for (std::size_t i = 0; i != c.materials.size(); ++i) {
    materials.insert(ctx, "M" + std::to_string(i + 1),
                     static_cast<int>(i + 1)) |
        or_die;
  }
  auto problem =
      construct<NonLinearEvolutionProblem>(
          ctx,
          Parameters{
              {"MeshFileName", c.mesh},
              {"FiniteElementFamily", "H1"},
              {"FiniteElementOrder", 1},
              {"UnknownsSize", 1},
              // the unit square has 900 elements
              {"NumberOfUniformRefinements", tridimensional ? 1 : 0},
              {"Materials", materials},
              {"Boundaries",
               Parameters{{"Xmin", xmin}, {"Xmax", xmax}, {"Ymax", ymax}}},
              {"Hypothesis", c.hypothesis},
              {"BehaviourIntegration", opts.integration},
              {"GradientsComputation", kernels},
              {"InnerForcesComputation", kernels},
              {"TangentOperatorComputation", tangent},
              {"Parallel", parallel}}) |
      or_die;
  problem.getUnknowns(bts) = 293.15;
  problem.getUnknowns(ets) = 293.15;
  // temperatures at the integration points of each material, external
  // state variable of the behaviour computed from the unknowns (the buffers
  // of the vectors are kept when the outer vector grows)
  auto temperatures = std::vector<std::vector<real>>{};
  for (std::size_t i = 0; i != c.materials.size(); ++i) {
    const auto name = "M" + std::to_string(i + 1);
    const auto& d = c.materials[i];
    problem.addBehaviourIntegrator(ctx, "StationaryNonLinearHeatTransfer", name,
                                   d.library, d.behaviour) |
        or_die;
    auto& m = problem.getMaterial(ctx, name, 0) | or_die;
    for (auto* s : {&m.s0, &m.s1}) {
      auto& T = temperatures.emplace_back(m.n, 293.15);
      mgis::behaviour::setExternalStateVariable(ctx, *s, "Temperature",
                                                std::span<real>(T)) |
          or_die;
    }
    if (m.b.symmetry == mgis::behaviour::Behaviour::ORTHOTROPIC) {
      setMaterialAxes(m, tridimensional, static_cast<int>(i));
    }
    if (c.transient) {
      problem.addBehaviourIntegrator(ctx, "TransientHeatTransfer", name,
                                     d.library, "HeatStorage") |
          or_die;
      // the gradient is the temperature at the integration points; the
      // external state variable `Temperature`, declared by all the
      // behaviours, is not used by `HeatStorage`
      auto& mt = problem.getMaterial(ctx, name, 1) | or_die;
      for (auto* s : {&mt.s0, &mt.s1}) {
        std::fill(s->gradients.begin(), s->gradients.end(), 293.15);
        mgis::behaviour::setExternalStateVariable(ctx, *s, "Temperature",
                                                  293.15) |
            or_die;
      }
    }
  }
  problem.addUniformDirichletBoundaryCondition(
      ctx, {{"Boundary", "Xmin"},
            {"Component", 0},
            {"LoadingEvolution", [](const real) noexcept { return 293.15; }}}) |
      or_die;
  problem.addUniformDirichletBoundaryCondition(
      ctx, {{"Boundary", "Xmax"},
            {"Component", 0},
            {"LoadingEvolution",
             [](const real t) noexcept { return 293.15 + 600 * t; }}}) |
      or_die;
  problem.addUniformDirichletBoundaryCondition(
      ctx, {{"Boundary", "Ymax"},
            {"Component", 0},
            {"LoadingEvolution",
             [](const real t) noexcept { return 293.15 + 1000 * t; }}}) |
      or_die;
  if (opts.matrix_free) {
    // the tangent operator of the heat transfer behaviours is negative
    // definite (`j = -k grad(T)`), and the diagonal of the essential degrees
    // of freedom is set to one: GMRES instead of the conjugate gradient
    problem.setLinearSolver(
        ctx, "GMRESSolver",
        {{"VerbosityLevel", 0},
         {"RelativeTolerance", 1e-12},
         {"AbsoluteTolerance", 0.},
         {"MaximumNumberOfIterations", 10000},
         {"KDim", 300},
         {"Preconditioner", Parameters{{"Name", "OperatorJacobiSmoother"}}}}) |
        or_die;
  } else {
    problem.setLinearSolver(ctx, parallel ? "MUMPSSolver" : "UMFPackSolver",
                            {}) |
        or_die;
  }
  if (opts.prediction) {
    problem.setPredictionPolicy(
        {.strategy = PredictionStrategy::BEGINNING_OF_TIME_STEP_PREDICTION,
         .prediction_operator = PredictionOperator::ELASTIC});
  }
  problem.setSolverParameters(ctx, {{"VerbosityLevel", 0},
                                    {"RelativeTolerance", 1e-12},
                                    {"AbsoluteTolerance", 0.},
                                    {"MaximumNumberOfIterations", 20}}) |
      or_die;
  auto r = Results{};
  constexpr int nsteps = 3;
  const auto dt = real{1} / nsteps;
  auto t = real{0};
  for (int i = 0; i != nsteps; ++i) {
    const auto o = problem.solve(ctx, t, dt);
    if (!o.status) {
      std::cerr << ctx.getErrorMessage() << '\n';
      return r;
    }
    r.iterations.push_back(static_cast<int>(o.iterations));
    problem.update(ctx) | or_die;
    t += dt;
  }
  const auto& u = problem.getUnknowns(ets);
  r.u.assign(u.HostRead(), u.HostRead() + u.Size());
  for (std::size_t i = 0; i != c.materials.size(); ++i) {
    const auto name = "M" + std::to_string(i + 1);
    auto& m = problem.getMaterial(ctx, name, 0) | or_die;
    m.synchronizeOnHostForReading();
    r.flux.insert(r.flux.end(), m.s1.thermodynamic_forces.begin(),
                  m.s1.thermodynamic_forces.end());
    // temperature at the integration points at the end of the last time
    // step
    const auto& T1 = temperatures[2 * i + 1];
    r.temperature.insert(r.temperature.end(), T1.begin(), T1.end());
    if (c.transient) {
      // rate of the enthalpy
      auto& mt = problem.getMaterial(ctx, name, 1) | or_die;
      mt.synchronizeOnHostForReading();
      r.flux.insert(r.flux.end(), mt.s1.thermodynamic_forces.begin(),
                    mt.s1.thermodynamic_forces.end());
    }
  }
  r.status = true;
  return r;
}  // end of compute

//! \return the maximum difference relative to the maximum absolute value
static double getRelativeDifference(const std::vector<mfem_mgis::real>& a,
                                    const std::vector<mfem_mgis::real>& b) {
  if ((a.size() != b.size()) || a.empty()) {
    return 1;
  }
  auto d = 0.;
  auto m = 0.;
  for (std::size_t i = 0; i != a.size(); ++i) {
    d = std::max(d, std::abs(a[i] - b[i]));
    m = std::max(m, std::abs(a[i]));
  }
  return m == 0 ? d : d / m;
}  // end of getRelativeDifference

/*!
 * \brief compares two computations
 * \param[in] a: reference
 * \param[in] b: computation
 * \param[in] name: name of the comparison
 */
static void compare(const Results& a,
                    const Results& b,
                    const std::string& name) {
  check(a.status, name + ": reference computation failed");
  check(b.status, name + ": computation failed");
  if (!(a.status && b.status)) {
    return;
  }
  const auto du = getRelativeDifference(a.u, b.u);
  const auto dj = getRelativeDifference(a.flux, b.flux);
  const auto dT = getRelativeDifference(a.temperature, b.temperature);
  std::cout << name << ": relative differences " << du << " (temperature), "
            << dj << " (heat flux), " << dT
            << " (temperature at the integration points)\n";
  check(du < 1e-10, name + ": temperature");
  check(dj < 1e-10, name + ": heat flux");
  check(dT < 1e-10, name + ": temperature at the integration points");
  check(a.iterations == b.iterations, name + ": numbers of iterations");
}  // end of compare

/*!
 * \return the problems
 * \param[in] cube: mesh of a cube
 * \param[in] two_materials: mesh of a cube made of two materials
 * \param[in] square: mesh of a unit square
 * \param[in] library: behaviour library
 */
static std::vector<Case> getCases(const char* const cube,
                                  const char* const two_materials,
                                  const char* const square,
                                  const char* const library) {
  const auto isotropic = MaterialDescription{.library = library};
  const auto orthotropic = MaterialDescription{
      .library = library,
      .behaviour = "OrthotropicStationaryNonLinearHeatTransfer"};
  auto cases = std::vector<Case>{};
  for (const auto& [n, h] : {std::pair{"3D", "Tridimensional"},
                             std::pair{"plane strain", "PlaneStrain"},
                             std::pair{"plane stress", "PlaneStress"}}) {
    const auto tridimensional = std::string_view{h} == "Tridimensional";
    const auto* const mesh = tridimensional ? cube : square;
    cases.push_back({.name = std::string{n} + ", isotropic",
                     .hypothesis = h,
                     .mesh = mesh,
                     .materials = {isotropic}});
    cases.push_back({.name = std::string{n} + ", orthotropic",
                     .hypothesis = h,
                     .mesh = mesh,
                     .materials = {orthotropic}});
    if (tridimensional) {
      cases.push_back({.name = std::string{n} + ", two materials",
                       .hypothesis = h,
                       .mesh = two_materials,
                       .materials = {isotropic, orthotropic}});
      cases.push_back({.name = std::string{n} + ", transient",
                       .hypothesis = h,
                       .mesh = two_materials,
                       .materials = {isotropic, orthotropic},
                       .transient = true});
    } else {
      cases.push_back({.name = std::string{n} + ", transient",
                       .hypothesis = h,
                       .mesh = mesh,
                       .materials = {orthotropic},
                       .transient = true});
    }
  }
  return cases;
}  // end of getCases

int main(int argc, char** argv) {
  using namespace mfem_mgis;
  initialize(argc, argv);
  const char* mesh = "cube.mesh";
  const char* two_materials_mesh = "cube-two-materials.mesh";
  const char* square_mesh = "cube2d.msh";
  const char* library = "src/libBehaviourTest.so";
  const char* openmp_library = "";
  const char* stlpar_library = "";
  const char* cuda_library = "";
  auto args = mfem::OptionsParser(argc, argv);
  declareDefaultOptions(args);
  args.AddOption(&mesh, "-m", "--mesh", "mesh of a cube");
  args.AddOption(&two_materials_mesh, "-m2", "--two-materials-mesh",
                 "mesh of a cube made of two materials");
  args.AddOption(&square_mesh, "-ms", "--square-mesh",
                 "two-dimensional mesh of the unit square");
  args.AddOption(&library, "-l", "--library",
                 "behaviour library (generic interface)");
  args.AddOption(&openmp_library, "-lo", "--openmp-library",
                 "behaviour library (generic-parallel interface, openmp)");
  args.AddOption(&stlpar_library, "-ls", "--stlpar-library",
                 "behaviour library (generic-parallel interface, stlpar)");
  args.AddOption(&cuda_library, "-lc", "--cuda-library",
                 "behaviour library (generic-parallel interface, cuda)");
  args.AddOption(&parallel, "-p", "--parallel", "-no-p", "--no-parallel",
                 "parallel computations");
  args.Parse();
  if (!args.Good()) {
    args.PrintUsage(std::cerr);
    return EXIT_FAILURE;
  }
  // libraries integrated by batches with the kernels: the behaviours of the
  // cuda backend are integrated on the GPU
  auto libraries =
      std::vector<std::pair<std::string, const char*>>{{"generic", library}};
  for (const auto& [name, l] :
       {std::pair{"openmp", openmp_library},
        std::pair{"stlpar", stlpar_library}, std::pair{"cuda", cuda_library}}) {
    if (std::string_view{l}.empty()) {
      continue;
    }
    libraries.emplace_back(name, l);
  }
  const auto references =
      getCases(mesh, two_materials_mesh, square_mesh, library);
  // the transient term changes the temperature
  for (std::size_t i = 0; i != references.size(); ++i) {
    if (!references[i].transient) {
      continue;
    }
    auto stationary = references[i];
    stationary.transient = false;
    const auto a = compute(stationary, {});
    const auto b = compute(references[i], {});
    if (a.status && b.status) {
      const auto d = getRelativeDifference(a.u, b.u);
      std::cout << references[i].name
                << ": relative difference with the stationary computation " << d
                << '\n';
      check(d > 1e-2, references[i].name + ": no effect of the transient term");
    }
  }
  for (const auto prediction : {false, true}) {
    for (std::size_t i = 0; i != references.size(); ++i) {
      const auto reference = compute(references[i], {.prediction = prediction});
      const auto suffix = references[i].name +
                          (prediction ? ", prediction" : ", no prediction");
      for (const auto& [lname, l] : libraries) {
        const auto c = getCases(mesh, two_materials_mesh, square_mesh, l)[i];
        // integration by batches with the computations element by element
        // (behaviours integrated on the host only)
        if (lname != "cuda") {
          compare(
              reference,
              compute(c, {.integration = "Batch", .prediction = prediction}),
              "batch, " + lname + ", " + suffix);
        }
        compare(reference,
                compute(c, {.integration = "Batch",
                            .kernels = true,
                            .prediction = prediction}),
                "kernels, " + lname + ", " + suffix);
        compare(reference,
                compute(c, {.integration = "Batch",
                            .kernels = true,
                            .matrix_free = true,
                            .prediction = prediction}),
                "kernels, matrix free, " + lname + ", " + suffix);
      }
    }
  }
  std::cout << (failures == 0 ? "success" : "failure") << '\n';
  return failures == 0 ? EXIT_SUCCESS : EXIT_FAILURE;
}  // end of main
