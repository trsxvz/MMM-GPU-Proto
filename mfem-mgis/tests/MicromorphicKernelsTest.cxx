/*!
 * \file   MicromorphicKernelsTest.cxx
 * \brief  Test of the computations by kernels of the micromorphic damage
 * behaviours (micromorphic damage and its gradient, the micromorphic damage
 * being the unknown): the integration by batches with the gradients, the
 * inner forces and the tangent operator computed by kernels (assembled, or
 * applied without assembly, whose diagonal is checked), with or without
 * elastic prediction, gives the results of the integration point by point,
 * in 3D, in plane strain and in
 * plane stress, for an isotropic behaviour and a rotated anisotropic one
 * whose tangent operator is not symmetric, for the behaviours generated by
 * the generic interface and, if given, by the generic-parallel interface.
 * \date   10/10/2026
 */

