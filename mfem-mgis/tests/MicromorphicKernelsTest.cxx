//! \brief number of failed checks
static int failures = 0;
//! \brief if true, the computations are parallel
static bool parallel = false;

static void check(const bool b, const std::string& msg) {
  if (!b) {
    std::cerr << "check failed: " << msg << '\n';
    ++failures;
  }
}  // end of check

//! \brief problem
struct Case {
  //! \brief name
  std::string name;
  //! \brief modelling hypothesis
  const char* hypothesis = "Tridimensional";
  //! \brief mesh: a cube or a unit square
  const char* mesh = "";
  //! \brief behaviour library
  const char* library = "";
  //! \brief behaviour
  const char* behaviour = "MicromorphicDamageII";
};

//! \brief options of a computation
struct ComputationOptions {
  //! \brief integration of the behaviour: `PointByPoint` or `Batch`
  const char* integration = "PointByPoint";
  //! \brief if true, the gradients, inner forces and tangent are kernels
  bool kernels = false;
  //! \brief if true, the tangent operator is applied without assembly
  bool matrix_free = false;
  //! \brief if true, an elastic prediction is made at each time step
  bool prediction = false;
};

//! \brief results of a computation
struct Results {
  //! \brief status
  bool status = false;
  //! \brief micromorphic damage at the nodes at the end of the computation
  std::vector<mfem_mgis::real> u;
  //! \brief dual forces at the integration points
  std::vector<mfem_mgis::real> forces;
  //! \brief damage at the integration points
  std::vector<mfem_mgis::real> damage;
  //! \brief number of Newton iterations of each time step
  std::vector<int> iterations;
};

/*!
 * \brief sets the material axes of an anisotropic behaviour: a rotation
 * around the z axis which is not a symmetry of the material, nor its own
 * inverse
 * \param[in] m: material
 * \param[in] tridimensional: if true, the computation is 3D
 */
static void setMaterialAxes(mfem_mgis::Material& m, const bool tridimensional) {
  using namespace mfem_mgis;
  const auto c = std::cos(0.3);
  const auto s = std::sin(0.3);
  const auto r = std::array<real, 9u>{c, s, 0, -s, c, 0, 0, 0, 1};
  if (tridimensional) {
    m.setRotationMatrix(RotationMatrix3D{r});
  } else {
    m.setRotationMatrix(RotationMatrix2D{r});
  }
}  // end of setMaterialAxes

/*!
 * \brief checks the diagonal of the tangent operator applied without
 * assembly (computed by kernels), the essential degrees of freedom being
 * constrained, against the diagonal of its assembled version
 * \param[in, out] problem: non linear evolution problem, after a resolution
 * and before the update of the materials
 * \param[in] name: name of the computation
 */
template <bool parallel_computation>
static void checkMatrixFreeDiagonal(
    mfem_mgis::NonLinearEvolutionProblem& problem, const std::string& name) {
  using namespace mfem_mgis;
  auto& p = problem.getImplementation<parallel_computation>();
  const auto& op = p.GetGradient(problem.getUnknowns(ets));
  const auto* const provider =
      dynamic_cast<const AssembledOperatorProvider*>(&op);
  if (provider == nullptr) {
    check(false, name + ": no assembled version of the tangent operator");
    return;
  }
  auto d = mfem::Vector(op.Height());
  op.AssembleDiagonal(d);
  const auto& a = provider->getAssembledOperator();
  auto da = mfem::Vector(op.Height());
  if (const auto* const sm = dynamic_cast<const mfem::SparseMatrix*>(&a);
      sm != nullptr) {
    sm->GetDiag(da);
  } else {
    a.AssembleDiagonal(da);
  }
  const auto* const pd = d.HostRead();
  const auto* const pa = da.HostRead();
  auto diff = real{0};
  auto m = mfem_mgis::real{0};
  for (int i = 0; i != d.Size(); ++i) {
    diff = std::max(diff, std::abs(pd[i] - pa[i]));
    m = std::max(m, std::abs(pa[i]));
  }
  check((d.Size() > 0) &&
            (diff <= mfem_mgis::unit_tests::tolerance(1e-12, 1e-5) * m),
        name + ": diagonal of the tangent operator applied without assembly");
}  // end of checkMatrixFreeDiagonal

/*!
 * \return the results of the computation
 * \param[in] c: problem
 * \param[in] opts: options
 */
static Results compute(const Case& c, const ComputationOptions& opts) {
  using namespace mfem_mgis;
  auto ctx = Context{};
  auto or_die = ctx.getFatalFailureHandler();
  const auto* const kernels = opts.kernels ? "Kernels" : "ElementByElement";
  const auto* const tangent = opts.matrix_free ? "MatrixFree" : kernels;
  const auto tridimensional =
      std::string_view{c.hypothesis} == "Tridimensional";
  // micromorphic damage imposed on x = 0, boundary 5 of the cube and 2 of
  // the unit square, increasing with time (the elastic prediction is made
  // from the increments of the imposed values), up to 2.5: the damage is
  // bounded by one near this boundary (a micromorphic damage greater than 2
  // is required with the material properties of this test)
  auto problem =
      construct<NonLinearEvolutionProblem>(
          ctx,
          Parameters{
              {"MeshFileName", c.mesh},
              {"FiniteElementFamily", "H1"},
              {"FiniteElementOrder", 1},
              {"UnknownsSize", 1},
              {"NumberOfUniformRefinements", tridimensional ? 1 : 0},
              {"Materials", Parameters{{"Body", 1}}},
              {"Boundaries", Parameters{{"Xmin", tridimensional ? 5 : 2}}},
              {"Hypothesis", c.hypothesis},
              {"BehaviourIntegration", opts.integration},
              {"GradientsComputation", kernels},
              {"InnerForcesComputation", kernels},
              {"TangentOperatorComputation", tangent},
              {"Parallel", parallel}}) |
      or_die;
  problem.addBehaviourIntegrator(ctx, "MicromorphicDamage", "Body", c.library,
                                 c.behaviour) |
      or_die;
  auto& m = problem.getMaterial(ctx, "Body", 0) | or_die;
  for (auto* s : {&m.s0, &m.s1}) {
    for (const auto& [n, v] : {std::pair{"FractureEnergy", 1.},
                               std::pair{"CharacteristicLength", 0.2},
                               std::pair{"PenalisationFactor", 1.}}) {
      mgis::behaviour::setMaterialProperty(ctx, *s, n, v) | or_die;
    }
    mgis::behaviour::setExternalStateVariable(ctx, *s, "Temperature", 293.15) |
        or_die;
  }
  if (m.b.symmetry == mgis::behaviour::Behaviour::ORTHOTROPIC) {
    setMaterialAxes(m, tridimensional);
  }
  // energy release rate, increasing with time, depending on all the
  // coordinates
  const auto Yr =
      tridimensional
          ? PartialQuadratureFunction::evaluate(
                m.getPartialQuadratureSpacePointer(),
                [](const real x, const real y, const real z) noexcept {
                  return 10 * (1 + std::sin(3 * x + 2 * y + z));
                })
          : PartialQuadratureFunction::evaluate(
                m.getPartialQuadratureSpacePointer(),
                [](const real x, const real y) noexcept {
                  return 10 * (1 + std::sin(3 * x + 2 * y));
                });
  const auto Yv = Yr->getValues();
  auto Y0 = std::vector<real>(Yv.size(), 0);
  auto Y1 = std::vector<real>(Yv.size(), 0);
  mgis::behaviour::setExternalStateVariable(
      ctx, m.s0, "EnergyReleaseRate", std::span<real>(Y0),
      mgis::behaviour::MaterialStateManager::EXTERNAL_STORAGE) |
      or_die;
  mgis::behaviour::setExternalStateVariable(
      ctx, m.s1, "EnergyReleaseRate", std::span<real>(Y1),
      mgis::behaviour::MaterialStateManager::EXTERNAL_STORAGE) |
      or_die;
  problem.addUniformDirichletBoundaryCondition(
      ctx, {{"Boundary", "Xmin"},
            {"Component", 0},
            {"LoadingEvolution",
             [](const real t) noexcept { return real{2.5} * t; }}}) |
      or_die;
  if (opts.matrix_free) {
    // the derivative of the dual force with respect to the gradient of the
    // micromorphic damage is not symmetric. The residual of the linear
    // solver must be well below the one of the Newton solver, whose
    // reference norm is small with the elastic prediction, to keep the same
    // numbers of iterations as with the direct solvers.
    problem.setLinearSolver(
        ctx, "GMRESSolver",
        {{"VerbosityLevel", 0},
         {"RelativeTolerance", 1e-14},
         {"AbsoluteTolerance", 0.},
         {"MaximumNumberOfIterations", 10000},
         {"KDim", 300},
         {"Preconditioner", Parameters{{"Name", "OperatorJacobiSmoother"}}}}) |
        or_die;
  } else {
    problem.setLinearSolver(
        ctx,
        parallel ? "MUMPSSolver"
                 : mfem_mgis::unit_tests::sequential_direct_solver,
        parallel
            ? mfem_mgis::Parameters{}
            : mfem_mgis::unit_tests::getSequentialDirectSolverParameters()) |
        or_die;
  }
  if (opts.prediction) {
    problem.setPredictionPolicy(
        {.strategy = PredictionStrategy::BEGINNING_OF_TIME_STEP_PREDICTION,
         .prediction_operator = PredictionOperator::ELASTIC});
  }
  problem.setSolverParameters(ctx, {{"VerbosityLevel", 0},
                                    {"RelativeTolerance", 1e-12},
                                    {"AbsoluteTolerance", 0.},
                                    {"MaximumNumberOfIterations", 20}}) |
      or_die;
  auto r = Results{};
  constexpr int nsteps = 3;
  const auto dt = real{1} / nsteps;
  auto t = real{0};
  for (int i = 0; i != nsteps; ++i) {
    // energy release rate decreasing at some points during some time steps:
    // the damage grows, stops or is bounded by one, depending on the point
    auto Y = [&Yv](const real ti, const std::size_t k) {
      return Yv[k] * ti * (1 + std::sin(6 * ti + static_cast<real>(k)));
    };
    for (std::size_t k = 0; k != Yv.size(); ++k) {
      Y0[k] = Y(t, k);
      Y1[k] = Y(t + dt, k);
    }
    const auto o = problem.solve(ctx, t, dt);
    if (!o.status) {
      std::cerr << ctx.getErrorMessage() << '\n';
      return r;
    }
    r.iterations.push_back(static_cast<int>(o.iterations));
    // diagonal of the tangent operator applied without assembly, after the
    // resolution of the last time step, before the update of the materials
    if ((opts.matrix_free) && (i + 1 == nsteps)) {
#ifdef MFEM_USE_MPI
      if (parallel) {
        checkMatrixFreeDiagonal<true>(problem, c.name);
      } else {
        checkMatrixFreeDiagonal<false>(problem, c.name);
      }
#else  /* MFEM_USE_MPI */
      checkMatrixFreeDiagonal<false>(problem, c.name);
#endif /* MFEM_USE_MPI */
    }
    problem.update(ctx) | or_die;
    t += dt;
  }
  const auto& u = problem.getUnknowns(ets);
  r.u.assign(u.HostRead(), u.HostRead() + u.Size());
  m.synchronizeOnHostForReading();
  r.forces.assign(m.s1.thermodynamic_forces.begin(),
                  m.s1.thermodynamic_forces.end());
  const auto od =
      mgis::behaviour::getVariableOffset(m.b.isvs, "Damage", m.b.hypothesis);
  const auto ns =
      static_cast<std::size_t>(m.s1.internal_state_variables_stride);
  for (std::size_t k = 0; k != Yv.size(); ++k) {
    r.damage.push_back(m.s1.internal_state_variables[k * ns + od]);
  }
  r.status = true;
  return r;
}  // end of compute

//! \return the maximum difference relative to the maximum absolute value
static double getRelativeDifference(const std::vector<mfem_mgis::real>& a,
                                    const std::vector<mfem_mgis::real>& b) {
  if ((a.size() != b.size()) || a.empty()) {
    return 1;
  }
  auto d = mfem_mgis::real{0};
  auto m = mfem_mgis::real{0};
  for (std::size_t i = 0; i != a.size(); ++i) {
    d = std::max(d, std::abs(a[i] - b[i]));
    m = std::max(m, std::abs(a[i]));
  }
  return m == 0 ? d : d / m;
}  // end of getRelativeDifference

/*!
 * \brief compares two computations
 * \param[in] a: reference
 * \param[in] b: computation
 * \param[in] name: name of the comparison
 */
static void compare(const Results& a,
                    const Results& b,
                    const std::string& name) {
  check(a.status, name + ": reference computation failed");
  check(b.status, name + ": computation failed");
  if (!(a.status && b.status)) {
    return;
  }
  const auto du = getRelativeDifference(a.u, b.u);
  const auto df = getRelativeDifference(a.forces, b.forces);
  const auto dd = getRelativeDifference(a.damage, b.damage);
  std::cout << name << ": relative differences " << du
            << " (micromorphic damage), " << df << " (dual forces), " << dd
            << " (damage)\n";
  // relative differences: in float, they reach 2.9e-5 for the dual forces
  // with the matrix free operator (roundings, and linear solvers stopping at
  // a relative residual of 1.2e-5)
  constexpr auto relative_tolerance =
      mfem_mgis::unit_tests::tolerance(1e-10, 3e-4);
  check(du < relative_tolerance, name + ": micromorphic damage");
  check(df < relative_tolerance, name + ": dual forces");
  check(dd < relative_tolerance, name + ": damage");
  // numbers of iterations: in float, the linear solvers stopping at a
  // relative residual of 1.2e-5, the Newton solver may need one more or one
  // less iteration with the matrix free operator
  constexpr auto iterations_tolerance =
      sizeof(mfem_mgis::real) == sizeof(double) ? 0 : 1;
  auto same_iterations = a.iterations.size() == b.iterations.size();
  for (std::size_t i = 0; same_iterations && (i != a.iterations.size()); ++i) {
    if (std::abs(a.iterations[i] - b.iterations[i]) > iterations_tolerance) {
      std::cout << name << ": time step " << i << ", " << a.iterations[i]
                << " iterations against " << b.iterations[i] << '\n';
      same_iterations = false;
    }
  }
  check(same_iterations, name + ": numbers of iterations");
}  // end of compare

/*!
 * \return the problems
 * \param[in] cube: mesh of a cube
 * \param[in] square: mesh of a unit square
 * \param[in] library: behaviour library
 */
static std::vector<Case> getCases(const char* const cube,
                                  const char* const square,
                                  const char* const library) {
  return {{.name = "3D, isotropic",
           .hypothesis = "Tridimensional",
           .mesh = cube,
           .library = library},
          {.name = "plane strain, isotropic",
           .hypothesis = "PlaneStrain",
           .mesh = square,
           .library = library},
          {.name = "plane strain, anisotropic",
           .hypothesis = "PlaneStrain",
           .mesh = square,
           .library = library,
           .behaviour = "OrthotropicMicromorphicDamage"},
          {.name = "plane stress, anisotropic",
           .hypothesis = "PlaneStress",
           .mesh = square,
           .library = library,
           .behaviour = "OrthotropicMicromorphicDamage"}};
}  // end of getCases

int main(int argc, char** argv) {
  using namespace mfem_mgis;
  initialize(argc, argv);
  const char* mesh = "cube.mesh";
  const char* square_mesh = "cube2d.msh";
  const char* library = "src/libBehaviourTest.so";
  const char* openmp_library = "";
  const char* stlpar_library = "";
  const char* cuda_library = "";
  auto print_references = false;
  auto args = mfem::OptionsParser(argc, argv);
  declareDefaultOptions(args);
  args.AddOption(&mesh, "-m", "--mesh", "mesh of a cube");
  args.AddOption(&square_mesh, "-ms", "--square-mesh",
                 "two-dimensional mesh of the unit square");
  args.AddOption(&library, "-l", "--library",
                 "behaviour library (generic interface)");
  args.AddOption(&openmp_library, "-lo", "--openmp-library",
                 "behaviour library (generic-parallel interface, openmp)");
  args.AddOption(&stlpar_library, "-ls", "--stlpar-library",
                 "behaviour library (generic-parallel interface, stlpar)");
  args.AddOption(&cuda_library, "-lc", "--cuda-library",
                 "behaviour library (generic-parallel interface, cuda)");
  args.AddOption(&parallel, "-p", "--parallel", "-no-p", "--no-parallel",
                 "parallel computations");
  args.AddOption(&print_references, "-pr", "--print-references", "-no-pr",
                 "--no-print-references",
                 "print the norms of the results of the integration point by "
                 "point, without the other computations");
  args.Parse();
  if (!args.Good()) {
    args.PrintUsage(std::cerr);
    return EXIT_FAILURE;
  }
  // libraries integrated by batches with the kernels: the behaviours of the
  // cuda backend are integrated on the GPU
  auto libraries =
      std::vector<std::pair<std::string, const char*>>{{"generic", library}};
  for (const auto& [name, l] :
       {std::pair{"openmp", openmp_library},
        std::pair{"stlpar", stlpar_library}, std::pair{"cuda", cuda_library}}) {
    if (std::string_view{l}.empty()) {
      continue;
    }
    libraries.emplace_back(name, l);
  }
  const auto references = getCases(mesh, square_mesh, library);
  for (const auto prediction : {false, true}) {
    for (std::size_t i = 0; i != references.size(); ++i) {
      const auto reference = compute(references[i], {.prediction = prediction});
      const auto suffix = references[i].name +
                          (prediction ? ", prediction" : ", no prediction");
      check(reference.status, suffix + ": reference computation failed");
      if (print_references) {
        // values of the integration point by point, to compare two versions
        // of the behaviour integrators
        auto n = [](const std::vector<real>& v) {
          auto s = real{0};
          for (const auto x : v) {
            s += x * x;
          }
          return std::sqrt(s);
        };
        std::cout << std::setprecision(17) << suffix << ": " << n(reference.u)
                  << ' ' << n(reference.forces) << ' ' << n(reference.damage)
                  << '\n';
        continue;
      }
      // the damage must evolve, and be bounded by one at some points (on
      // all the processes)
      auto dmin = std::numeric_limits<real>::max();
      auto dmax = std::numeric_limits<real>::lowest();
      for (const auto d : reference.damage) {
        dmin = std::min(dmin, d);
        dmax = std::max(dmax, d);
      }
#ifdef MFEM_USE_MPI
      if (parallel) {
        MPI_Allreduce(MPI_IN_PLACE, &dmin, 1, mfem_mgis::mpi_type<real>,
                      MPI_MIN, MPI_COMM_WORLD);
        MPI_Allreduce(MPI_IN_PLACE, &dmax, 1, mfem_mgis::mpi_type<real>,
                      MPI_MAX, MPI_COMM_WORLD);
      }
#endif /* MFEM_USE_MPI */
      check(dmax - dmin > 1e-2, suffix + ": uniform damage");
      check(dmax > 1 - 1e-12,
            suffix + ": the damage is not bounded by one at any point");
      for (const auto& [lname, l] : libraries) {
        auto c = getCases(mesh, square_mesh, l)[i];
        // integration by batches with the computations element by element
        // (behaviours integrated on the host only)
        if (lname != "cuda") {
          compare(
              reference,
              compute(c, {.integration = "Batch", .prediction = prediction}),
              "batch, " + lname + ", " + suffix);
        }
        compare(reference,
                compute(c, {.integration = "Batch",
                            .kernels = true,
                            .prediction = prediction}),
                "kernels, " + lname + ", " + suffix);
        compare(reference,
                compute(c, {.integration = "Batch",
                            .kernels = true,
                            .matrix_free = true,
                            .prediction = prediction}),
                "kernels, matrix free, " + lname + ", " + suffix);
      }
    }
  }
  std::cout << (failures == 0 ? "success" : "failure") << '\n';
  return failures == 0 ? EXIT_SUCCESS : EXIT_FAILURE;
}  // end of main
